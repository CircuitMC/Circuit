#!/usr/bin/env python3
"""Compiles a packet id table from the public protocol documentation.

Input is the wikitext of a cited revision of minecraft.wiki's
"Java Edition protocol/Packets" page. Each documented packet lists its
protocol id, resource name, state and direction; ids within one state and
direction must be contiguous from 0. The output is a C++ source file used by
the version adapter. Fetch a revision with:

  curl -s "https://minecraft.wiki/api.php?action=parse&oldid=<revid>&prop=wikitext&format=json" \\
    | python3 -c "import json,sys; print(json.load(sys.stdin)['parse']['wikitext']['*'])" > packets.wiki
"""
import argparse
import re
import sys
from collections import defaultdict

STATES = {"Handshaking": "handshaking", "Status": "status", "Login": "login",
          "Configuration": "configuration", "Play": "play"}
BOUNDS = {"Server": "serverbound", "Client": "clientbound"}
ROW = re.compile(
    r"''protocol:''<br/><code>(0x[0-9A-Fa-f]+)</code><br/><br/>''resource:''<br/><code>([a-z_]+)</code>\s*\n"
    r"\s*\|\s*(?:rowspan=\"\d+\"\s*\|)?\s*([A-Za-z]+)\s*\n\s*\|\s*(?:rowspan=\"\d+\"\s*\|)?\s*([A-Za-z]+)")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("wikitext")
    parser.add_argument("--protocol", type=int, required=True)
    parser.add_argument("--revision", type=int, required=True)
    parser.add_argument("--symbol", required=True, help="C++ table name, e.g. packets_772")
    parser.add_argument("--output", required=True)
    args = parser.parse_args()

    text = open(args.wikitext, encoding="utf-8").read()
    groups = defaultdict(dict)
    for pid, resource, state, bound in ROW.findall(text):
        if state not in STATES or bound not in BOUNDS:
            sys.exit(f"unknown state or direction: {state} {bound}")
        key = (STATES[state], BOUNDS[bound])
        if resource in groups[key]:
            sys.exit(f"duplicate resource {resource} in {key}")
        groups[key][resource] = int(pid, 16)
    total = 0
    for key, packets in groups.items():
        ids = sorted(packets.values())
        if ids != list(range(len(ids))):
            sys.exit(f"ids in {key} are not contiguous from 0: {ids}")
        total += len(ids)
    if not groups:
        sys.exit("no packets found")

    lines = [
        "// SPDX-License-Identifier: AGPL-3.0-only",
        f"// Generated by tools/extract_packet_ids.py from minecraft.wiki \"Java Edition protocol/Packets\",",
        f"// revision {args.revision} (protocol {args.protocol}). Do not edit by hand; re-run the tool.",
        '#include "packet_tables.hpp"',
        "",
        "namespace circuit::protocol::detail {",
        "",
        f"const PacketTable {args.symbol}{{{args.protocol}, {args.revision}, {{",
    ]
    for (state, bound) in sorted(groups, key=lambda k: (list(STATES.values()).index(k[0]), k[1])):
        for resource, pid in sorted(groups[(state, bound)].items(), key=lambda kv: kv[1]):
            lines.append(f"    {{State::{state}, Bound::{bound}, 0x{pid:02x}, \"{resource}\"}},")
    lines += ["}};", "", "} // namespace circuit::protocol::detail", ""]
    with open(args.output, "w", encoding="utf-8") as out:
        out.write("\n".join(lines))
    print(f"{total} packets written to {args.output}")


if __name__ == "__main__":
    main()
