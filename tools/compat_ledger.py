class Sources:
    """The hand-written files below one compatibility directory. Reading a
    file notes it when it is not in canonical form; a file that cannot be
    read as intended is a Failure."""

    def __init__(self, compat):
        self.compat = compat
        self.files = {}   # relative path -> (text, data)

    def path(self, *parts):
        return os.path.join(self.compat, *parts)

    def load(self, rel, required=()):
        def pairs(items):
            keys = [k for k, _ in items]
            for k in keys:
                if keys.count(k) > 1:
                    raise Failure(f"compatibility/{rel}: key {k} is given twice")
            return dict(items)
        try:
            text = read_text(self.path(rel))
            data = json.loads(text, object_pairs_hook=pairs)
        except (OSError, ValueError) as e:
            raise Failure(f"compatibility/{rel}: {e}")
        if not isinstance(data, dict):
            raise Failure(f"compatibility/{rel}: not an object")
        for key in required:
            if key not in data:
                raise Failure(f"compatibility/{rel}: lacks {key}")
        self.files[rel] = (text, data)
        return data

    def directories(self, rel):
        """Subdirectories of a directory, sorted; anything else in it must be a file named _*.json."""
        out = []
        for name in sorted(os.listdir(self.path(rel))):
            if name.startswith("."):
                continue
            if os.path.isdir(self.path(rel, name)):
                out.append(name)
            elif not re.fullmatch(r"_[a-z_]+\.json", name):
                raise Failure(f"compatibility/{rel}/{name}: unexpected file")
        return out

    def entries(self, rel, part):
        """Entry files below a directory as {name: relative path}. A name is
        the path below the directory without its extension, each part
        matching `part`; files named _*.json belong to the directory itself."""
        out = {}
        top = self.path(rel)
        for base, dirs, files in os.walk(top):
            dirs[:] = sorted(d for d in dirs if not d.startswith("."))
            for name in sorted(files):
                if name.startswith(".") or (base == top and re.fullmatch(r"_[a-z_]+\.json", name)):
                    continue
                below = os.path.relpath(os.path.join(base, name), top).replace(os.sep, "/")
                entry = below[: -len(".json")]
                if not name.endswith(".json") or not all(re.fullmatch(part, p) for p in entry.split("/")):
                    raise Failure(f"compatibility/{rel}/{below}: unexpected file")
                out[entry] = f"{rel}/{below}"
        return out

    def errors(self):
        return [f"compatibility/{rel}: not in canonical form (run tools/compat_ledger.py format)"
                for rel, (text, data) in sorted(self.files.items()) if text != canonical(data)]


def versions():
    return Sources(COMPAT).load("families/_index.json")["versions"]


def per_version(value, bundles, default=None):
    """A field given for both versions, or per version."""
    if isinstance(value, dict):
        return {b: value.get(b, default) for b in bundles}
    return {b: (value if value is not None else default) for b in bundles}


def open_outcomes(directory):
    """Outcomes of the open traces Circuit does not match yet (EXPECTED.txt)."""
    out = {}
    for line in read_text(os.path.join(directory, "EXPECTED.txt")).splitlines():
        if line and not line.startswith("#"):
            name, outcome = line.split(" ")[:2]
            out[name] = {"FAIL": "failing", "UNSUPPORTED": "unsupported"}[outcome]
    return out


def trace_cases(bundles):
    """Every target-version trace is a case: passing ones from the harness
    directories, failing or unsupported ones from the open directories.
    Returns the cases and the blocks each passing trace places."""
    cases = {}
    blocks = defaultdict(set)
    for bundle in bundles:
        schemas = load(os.path.join(COMPAT, "versions", f"{bundle}.json"))["circuit_schemas"]
        sources = [(os.path.join(ROOT, schemas["reference_traces"]), None)]
        if schemas.get("open_traces"):
            open_dir = os.path.join(ROOT, schemas["open_traces"])
            sources.append((open_dir, open_outcomes(open_dir)))
        for d, outcomes in sources:
            for name in sorted(os.listdir(d)):
                if not name.endswith(".ctrace"):
                    continue
                stem = name[: -len(".ctrace")]
                text = read_text(os.path.join(d, name))
                header = dict(line.split(" ", 1) for line in text.splitlines()[:16] if " " in line)
                status = "passing" if outcomes is None else outcomes[name]
                case = cases.setdefault(f"trace/{stem}", {
                    "id": f"trace/{stem}", "kind": "official_trace", "versions": [], "status": status,
                    "location": f"{os.path.relpath(d, ROOT)}/{name}", "description": header.get("title", stem),
                    "mechanisms": header.get("mechanisms", "").split()})
                if case["status"] != status:
                    raise Failure(f"trace/{stem}: {case['status']} on one version, {status} on another")
                case["versions"].append(bundle)
                if status == "passing":
                    for block in set(re.findall(r"minecraft:([a-z_]+)", text)):
                        blocks[(bundle, block)].add(f"trace/{stem}")
    return cases, blocks


def referenced_packets(directory=None):
    """Packet names the server code looks up, as state/bound/name, in every
    source file below src/server."""
    out = set()
    for base, dirs, files in os.walk(directory or os.path.join(ROOT, "src", "server")):
        dirs.sort()
        for name in sorted(files):
            if not name.endswith(".cpp"):
                continue
            text = read_text(os.path.join(base, name))
            for short, state, packet in re.findall(r"\b(cb|sb)\(State::(\w+), \"(\w+)\"\)", text):
                out.add(f"{state}/{'clientbound' if short == 'cb' else 'serverbound'}/{packet}")
            for bound, state, packet in re.findall(r"\b(serverbound|clientbound)\(State::(\w+), \"(\w+)\"\)", text):
                out.add(f"{state}/{bound}/{packet}")
    return out


def classify(rules, kind, name, block_family):
    for family, pattern in rules[kind]:
        if family == "block":
            if name in block_family:
                return block_family[name]
            continue
        if re.search(pattern, name):
            return family
    raise Failure(f"{kind} {name}: no classification rule matches")


