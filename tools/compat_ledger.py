def produce(inputs=None):
    """Builds and validates the ledger; returns it, the manifests and the errors."""
    REFERENCED.clear()
    REFERENCED.update(referenced_packets())
    inputs = inputs if inputs is not None else read_inputs()
    try:
        ledger, manifests, family_ids = build(inputs)
    except Failure as e:
        return None, inputs["manifests"], [str(e)]
    errors = validate(ledger, manifests, family_ids, inputs)
    return ledger, manifests, errors


def cmd_generate(args):
    ledger, manifests, errors = produce()
    if errors:
        for e in errors:
            print(f"error: {e}", file=sys.stderr)
        sys.exit(1)
    with open(LEDGER, "w", encoding="utf-8") as f:
        f.write(ledger_text(ledger))
    with open(SUMMARY, "w", encoding="utf-8") as f:
        f.write(summary(ledger, manifests) + "\n")
    with open(PACKAGES, "w", encoding="utf-8") as f:
        f.write(packages_summary(ledger, manifests) + "\n")
    print(f"{len(ledger['features'])} features, {len(ledger['cases'])} cases")


def cmd_check(args):
    ledger, manifests, errors = produce()
    if ledger is None:
        for e in errors:
            print(f"error: {e}", file=sys.stderr)
        sys.exit(1)
    if not args.sources_only:
        if not os.path.exists(LEDGER) or read_text(LEDGER) != ledger_text(ledger):
            errors.append("compatibility/ledger.json is out of date: run tools/compat_ledger.py generate")
        if not os.path.exists(SUMMARY) or read_text(SUMMARY) != summary(ledger, manifests) + "\n":
            errors.append("docs/VANILLA_LEDGER.md is out of date: run tools/compat_ledger.py generate")
        if not os.path.exists(PACKAGES) or read_text(PACKAGES) != packages_summary(ledger, manifests) + "\n":
            errors.append("compatibility/PACKAGES.md is out of date: run tools/compat_ledger.py generate")
    for e in errors:
        print(f"error: {e}", file=sys.stderr)
    if errors:
        sys.exit(1)
    print(f"compatibility ledger: {len(ledger['features'])} features, {len(ledger['cases'])} cases, valid"
          + (" (generated files not compared)" if args.sources_only else ""))


def cmd_format(args):
    src = Sources(COMPAT)
    src.load("packages.json")
    for base, dirs, files in os.walk(COMPAT):
        dirs[:] = sorted(d for d in dirs if d not in ("inventory", "versions") or base != COMPAT)
        if base == COMPAT:
            continue
        for name in sorted(files):
            if name.endswith(".json"):
                src.load(os.path.relpath(os.path.join(base, name), COMPAT).replace(os.sep, "/"))
    changed = 0
    for rel, (text, data) in sorted(src.files.items()):
        if text != canonical(data):
            with open(src.path(rel), "w", encoding="utf-8") as f:
                f.write(canonical(data))
            changed += 1
    print(f"{len(src.files)} files, {changed} rewritten")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    inv = sub.add_parser("inventory")
    inv.add_argument("--mcdata", required=True)
    sub.add_parser("generate")
    check = sub.add_parser("check")
    check.add_argument("--sources-only", action="store_true")
    sub.add_parser("format")
    args = parser.parse_args()
    try:
        {"inventory": cmd_inventory, "generate": cmd_generate, "check": cmd_check, "format": cmd_format}[args.command](args)
    except Failure as e:
        print(f"error: {e}", file=sys.stderr)
