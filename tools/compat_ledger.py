def read_inputs(compat=None):
    """The hand-written and inventory documents, as build() takes them: the
    per-entry files joined into one document for the families, one for the
    resources and one for the cases."""
    src = Sources(compat or COMPAT)
    index = src.load("families/_index.json", ("schema", "versions"))
    bundles = index["versions"]
    families = []
    for fid in src.directories("families"):
        head = src.load(f"families/{fid}/_family.json", ("name", "milestones"))
        files = src.entries(f"families/{fid}", r"[a-z][a-z0-9_]*")
        if any("/" in m for m in files):
            raise Failure(f"compatibility/families/{fid}: mechanics are files of the family's directory")
        order = head.get("mechanics", [])
        for m in order:
            if m not in files or order.count(m) > 1:
                raise Failure(f"compatibility/families/{fid}/_family.json: mechanic {m} is listed {'twice' if m in files else 'but has no file'}")
        # Listed mechanics come first, in the listed order; the others follow by id.
        ids = order + sorted(set(files) - set(order))
        families.append({"id": fid, "name": head["name"], "milestones": head["milestones"],
                         "mechanics": [{"id": m, **src.load(files[m], ("name", "milestone", "impl"))} for m in ids]})
    resources_index = src.load("resources/_index.json", ("schema",))
    kinds = src.directories("resources")
    if sorted(kinds) != sorted(NAMED_KINDS):
        raise Failure(f"compatibility/resources: its directories must be the kinds {', '.join(sorted(NAMED_KINDS))}")
    defaults, classification, overrides = {}, {}, {}
    for kind in kinds:
        head = src.load(f"resources/{kind}/_kind.json", ("defaults", "classification"))
        defaults[kind] = head["defaults"]
        classification[kind] = head["classification"]
        overrides[kind] = {name: src.load(rel) for name, rel in src.entries(f"resources/{kind}", r"[a-z0-9][a-z0-9_]*").items()}
    cases_index = src.load("cases/_index.json", ("schema",))
    case_keys = ("kind", "versions", "location", "status", "description")
    cases = [{"id": name, **src.load(rel, case_keys)} for name, rel in src.entries("cases", r"[A-Za-z0-9][A-Za-z0-9_-]*").items()]
    families_doc = {"schema": index["schema"], "versions": bundles, "families": families, "classification": classification,
                    "inventories_unknown": src.load("families/_inventories_unknown.json", ("inventories",))["inventories"]}
    return {
        "families": families_doc,
        "resources": {"schema": resources_index["schema"], "defaults": defaults, "overrides": overrides},
        "cases": {"schema": cases_index["schema"], "cases": cases},
        "packages": src.load("packages.json", ("schema", "packages")),
        "manifests": {b: load(src.path("versions", f"{b}.json")) for b in bundles},
        "inventories": {b: load(src.path("inventory", f"{b}.json")) for b in bundles},
        "source_errors": src.errors(),
    }


def build(inputs):
    families_doc = inputs["families"]
    bundles = families_doc["versions"]
    resources = inputs["resources"]
    case_doc = inputs["cases"]
    manifests = inputs["manifests"]
    inventories = inputs["inventories"]
    traces, trace_blocks = trace_cases(bundles)
    cases = dict(traces)
    for c in case_doc["cases"]:
        if c["id"] in cases:
            raise Failure(f"case {c['id']} is defined twice")
        cases[c["id"]] = c
    family_ids = [f["id"] for f in families_doc["families"]]
    family_by_id = {f["id"]: f for f in families_doc["families"]}
    rules = families_doc["classification"]

    features = []

    def add(feature):
        features.append(feature)

    for family in families_doc["families"]:
        for m in family["mechanics"]:
            impl = per_version(m.get("impl"), bundles)
            evidence = per_version(m.get("evidence", "none"), bundles, "none")
            reasons = per_version(m.get("absent_reason", {}), bundles)
            records = {}
            for b in bundles:
                rec = {"impl": impl[b], "evidence": evidence[b]}
                if impl[b] == "not_applicable":
                    rec["reason"] = reasons[b]
                rec["cases"] = [c for c in m.get("cases", []) if b in cases.get(c, {}).get("versions", [b])]
                if m.get("deviations"):
                    rec["deviations"] = m["deviations"]
                records[b] = rec
            feature = {"id": f"{family['id']}.{m['id']}", "family": family["id"], "kind": "mechanic", "name": m["name"],
                       "milestone": m["milestone"], "tier": m.get("tier", "L0"), "versions": records}
            for key in ("note", "cases_planned", "prerequisites", "packages"):
                if key in m:
                    feature[key] = m[key]
            add(feature)

    # Enumerated resources: one feature per name and kind, over the union of versions.
    block_family = {}
    for kind in NAMED_KINDS:
        names = sorted(set().union(*(set(inventories[b]["kinds"][kind]["names"]) for b in bundles)))
        defaults = resources["defaults"][kind]
        overrides = resources["overrides"].get(kind, {})
        for name in names:
            family = classify(rules, kind, name, block_family)
            if kind == "block":
                block_family[name] = family
            override = overrides.get(name, {})
            records = {}
            for b in bundles:
                present = name in inventories[b]["kinds"][kind]["names"]
                if not present:
                    records[b] = {"impl": "not_applicable", "evidence": "none",
                                  "reason": f"not in {manifests[b]['release']}", "cases": []}
                    continue
                spec = {**defaults, **override}
                if kind == "packet":
                    if name in REFERENCED and "impl" not in override:
                        spec["impl"] = "partial"
                rec = {"impl": per_version(spec["impl"], bundles)[b], "evidence": per_version(spec.get("evidence", "none"), bundles)[b]}
                linked = list(spec.get("cases", []))
                if kind == "block":
                    linked += sorted(trace_blocks.get((b, name), ()))
                rec["cases"] = sorted({c for c in linked if b in cases.get(c, {}).get("versions", [b])})
                if spec.get("deviations"):
                    rec["deviations"] = spec["deviations"]
                records[b] = rec
            feature = {"id": f"{kind}/{name}" if kind == "packet" else f"{kind}/minecraft:{name}", "family": family,
                       "kind": kind, "name": name, "milestone": override.get("milestone", family_by_id[family]["milestones"][0]), "tier": "L0",
                       "versions": records}
            if override.get("note"):
                feature["note"] = override["note"]
            add(feature)

    for m in families_doc["inventories_unknown"]:
        add({"id": f"inventory/{m['id']}", "family": m["family"], "kind": "inventory", "name": m["id"],
             "milestone": m["milestone"], "tier": "L0", "note": m["note"],
             "versions": {b: {"impl": "missing", "evidence": "none", "count": None, "cases": []} for b in bundles}})

    ledger = {
        "schema": "circuit-compatibility-ledger-1",
        "comment": "Generated by tools/compat_ledger.py; do not edit.",
        "versions": bundles,
        "families": [{"id": f["id"], "name": f["name"], "milestones": f["milestones"]} for f in families_doc["families"]],
        "packages": [dict(p) for p in inputs["packages"]["packages"]],
        "kind_notes": {k: v["note"] for k, v in resources["defaults"].items() if v.get("note")},
        "inventories": {b: {k: ({"source": v["source"], "exact": v["exact"], "count": len(v["names"]) if "names" in v else v["count"]})
                            for k, v in inventories[b]["kinds"].items()} for b in bundles},
        "cases": [cases[k] for k in sorted(cases)],
        "features": features,
    }
    return ledger, manifests, family_ids


REFERENCED = set()


def ledger_text(ledger):
    """The ledger as JSON with one feature, case or family per line."""
    lines = ["{"]
    keys = list(ledger)
    for i, key in enumerate(keys):
        value = ledger[key]
        tail = "," if i + 1 < len(keys) else ""
        if isinstance(value, list) and value and isinstance(value[0], dict):
            lines.append(f" {json.dumps(key)}: [")
            for j, item in enumerate(value):
                lines.append("  " + json.dumps(item, ensure_ascii=False, sort_keys=True) + ("," if j + 1 < len(value) else ""))
            lines.append(" ]" + tail)
        else:
            lines.append(f" {json.dumps(key)}: " + json.dumps(value, ensure_ascii=False, sort_keys=True) + tail)
    lines.append("}")
    return "\n".join(lines) + "\n"


