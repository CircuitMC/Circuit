def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def read_text(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def dump(path, data):
    text = json.dumps(data, indent=1, ensure_ascii=False) + "\n"
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def canonical(data):
    """The form of a hand-written source file."""
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


class Failure(Exception):
    pass


# ---- inventory ---------------------------------------------------------------

def snake(name):
    if name == "BadLuck":
        return "unluck"  # the registry name of Bad Luck (minecraft.wiki "Effect")
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def packet_names(protocol):
    path = os.path.join(ROOT, "src", "protocol", f"packets_{protocol}.cpp")
    text = read_text(path)
    states = {"handshaking": "handshaking", "status": "status", "login": "login", "configuration": "configuration", "play": "play"}
    out = []
    for state, bound, name in re.findall(r"\{State::(\w+), Bound::(\w+), 0x[0-9a-fA-F]+, \"(\w+)\"\}", text):
        out.append(f"{states[state]}/{bound}/{name}")
    if not out:
        raise Failure(f"{path}: no packets found")
    return sorted(set(out))


def damage_types():
    text = read_text(os.path.join(ROOT, "src", "server", "registries.cpp"))
    m = re.search(r"\{\"minecraft:damage_type\",\s*\{(.*?)\}\}", text, re.S)
    if not m:
        raise Failure("src/server/registries.cpp: no damage-type registry")
    return sorted(n.split(":", 1)[1] for n in re.findall(r"\"(minecraft:[a-z_]+)\"", m.group(1)))


def cmd_inventory(args):
    paths = load(os.path.join(args.mcdata, "dataPaths.json"))["pc"]
    for bundle in versions():
        manifest = load(os.path.join(COMPAT, "versions", f"{bundle}.json"))
        release = manifest["release"]
        commit = manifest["public_data"]["commit"]
        mapped = paths[release]
        tables = os.path.join(args.mcdata, release, "tables")

        def table(kind):
            return load(os.path.join(tables, f"{kind}.json"))

        def source(kind):
            return {"source": f"minecraft-data {mapped[kind]}/{kind}.json", "exact": mapped[kind] == f"pc/{release}"}

        blocks = table("blocks")
        kinds = {
            "block": {**source("blocks"), "names": sorted(b["name"] for b in blocks)},
            "block_state": {**source("blocks"), "count": sum(b["maxStateId"] - b["minStateId"] + 1 for b in blocks)},
            "item": {**source("items"), "names": sorted(i["name"] for i in table("items") if i["name"] != "air")},
            "entity": {**source("entities"), "names": sorted(e["name"] for e in table("entities"))},
            "effect": {**source("effects"), "names": sorted(snake(e["name"]) for e in table("effects")),
                       "note": "registry names converted from minecraft-data's effect names"},
            "enchantment": {**source("enchantments"), "names": sorted(e["name"] for e in table("enchantments"))},
            "attribute": {**source("attributes"), "names": sorted(a["resource"].split(":", 1)[1] for a in table("attributes"))},
            "biome": {**source("biomes"), "names": sorted(b["name"] for b in table("biomes"))},
            "particle": {**source("particles"), "names": sorted(p["name"] for p in table("particles"))},
            "command": {**source("commands"), "names": sorted(c["name"] for c in table("commands")["root"]["children"]),
                        "note": "top-level commands of the command tree"},
            "sound_event": {**source("sounds"), "count": len(table("sounds"))},
            "recipe": {**source("recipes"), "count": sum(len(v) for v in table("recipes").values()),
                       "note": "crafting recipes as minecraft-data lists them"},
            "instrument": {**source("instruments"), "count": len(table("instruments"))},
            "damage_type": {"source": "src/server/registries.cpp (minecraft.wiki \"Damage type\")", "exact": True, "names": damage_types()},
            "packet": {"source": f"src/protocol/packets_{manifest['protocol']}.cpp (minecraft.wiki protocol tables)", "exact": True,
                       "names": packet_names(manifest["protocol"])},
        }
        dump(os.path.join(COMPAT, "inventory", f"{bundle}.json"),
             {"schema": "circuit-compatibility-inventory-1", "bundle": bundle, "release": release,
              "public_data_commit": commit, "kinds": kinds})
        print(f"{bundle}: " + ", ".join(f"{k} {len(v['names']) if 'names' in v else v['count']}" for k, v in kinds.items()))


