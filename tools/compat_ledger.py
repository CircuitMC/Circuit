def summary(ledger, manifests):
    bundles = ledger["versions"]
    feats = ledger["features"]
    out = []
    w = out.append
    w("# Vanilla compatibility ledger")
    w("")
    w("Generated by `tools/compat_ledger.py` from the files in [`compatibility/`](../compatibility/); do not edit. "
      "The ledger records, for each target version, which vanilla features Circuit implements and what evidence supports each claim. "
      "Its families and milestones are those of the [vanilla completion roadmap](VANILLA_COMPLETION.md). "
      "The mechanics that are not implemented are grouped into [work packages](../compatibility/PACKAGES.md).")
    w("")
    w("**Implementation states:** `implemented` (complete for the feature as described), `partial` (some behavior, with listed gaps), "
      "`data_only` (named in registries or storage, with no behavior), `missing`, and `not_applicable` (absent from that version, with the reason). "
      "**Evidence states:** `compared` (Circuit compared with the official server for named cases), `reference_only` (official observations, "
      "Circuit not compared), `documented` (public documentation only), `mismatch` (a comparison shows a difference) and `none`. "
      "Counts of different kinds of features are not comparable, so no overall percentage is given.")
    w("")
    w("## Versions")
    w("")
    w("| | " + " | ".join(manifests[b]["release"] for b in bundles) + " |")
    w("| --- | " + " | ".join("---" for _ in bundles) + " |")
    rows = [
        ("Protocol", lambda m: str(m["protocol"])),
        ("DataVersion", lambda m: str(m["data_version"])),
        ("Data / resource pack format", lambda m: f"{m['pack_formats']['data']} / {m['pack_formats']['resource']}"),
        ("Server jar SHA-1", lambda m: f"`{next(a for a in m['reference_artifacts'] if a['kind'] == 'server')['sha1']}`"),
        ("Client jar SHA-1", lambda m: f"`{next(a for a in m['reference_artifacts'] if a['kind'] == 'client')['sha1']}`"),
        ("Profiles", lambda m: ", ".join(f"{p['id']} ({p['status']})" for p in m["profiles"])),
        ("Public data", lambda m: f"minecraft-data `{m['public_data']['commit'][:8]}`"),
    ]
    for label, f in rows:
        w(f"| {label} | " + " | ".join(f(manifests[b]) for b in bundles) + " |")
    w("")
    w("The values were read from the official jars, whose hashes equal Mojang's published version metadata.")
    w("")
    w("## Families")
    w("")
    w("Feature counts per implementation state, then the number of features with compared evidence. "
      "Each cell lists 1.21.4 / 1.21.8.")
    w("")
    w("| Family | Milestones | Features | Implemented | Partial | Data only | Missing | Not applicable | Compared |")
    w("| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |")
    for fam in ledger["families"]:
        fs = [f for f in feats if f["family"] == fam["id"]]

        def cell(pred):
            return " / ".join(str(sum(1 for f in fs if pred(f["versions"][b]))) for b in bundles)
        w(f"| {fam['id']} {fam['name']} | {', '.join(fam['milestones'])} | {len(fs)} | "
          + " | ".join(cell(lambda r, s=s: r["impl"] == s) for s in ["implemented", "partial", "data_only", "missing", "not_applicable"])
          + f" | {cell(lambda r: r['evidence'] == 'compared')} |")
    w("")
    w("## Enumerated resources")
    w("")
    w("One feature per name. Inventories marked approximate come from a minecraft-data table of an earlier release.")
    w("")
    w("| Kind | Source | Count | Implemented | Partial | Data only | Missing |")
    w("| --- | --- | ---: | ---: | ---: | ---: | ---: |")
    for kind in NAMED_KINDS + COUNTED_KINDS:
        srcs = " / ".join(("" if ledger["inventories"][b][kind]["exact"] else "approximate: ") + ledger["inventories"][b][kind]["source"] for b in bundles)
        count = " / ".join(str(ledger["inventories"][b][kind]["count"]) for b in bundles)
        if kind in COUNTED_KINDS:
            w(f"| {kind} | {srcs} | {count} | — | — | — | — |")
            continue
        fs = [f for f in feats if f["kind"] == kind]

        def cell(state):
            return " / ".join(str(sum(1 for f in fs if f["versions"][b]["impl"] == state)) for b in bundles)
        w(f"| {kind} | {srcs} | {count} | {cell('implemented')} | {cell('partial')} | {cell('data_only')} | {cell('missing')} |")
    w("")
    w("## Version differences")
    w("")
    for kind in NAMED_KINDS:
        only = {b: sorted(f["name"] for f in feats if f["kind"] == kind and all(
            (r["impl"] == "not_applicable") != (o == b) for o, r in f["versions"].items())) for b in bundles}
        if any(only.values()):
            parts = [f"only in {manifests[b]['release']} ({len(n)}): {', '.join(n[:40])}{', …' if len(n) > 40 else ''}" for b, n in only.items() if n]
            w(f"- **{kind}:** " + "; ".join(parts) + ".")
    for f in feats:
        if f["kind"] == "mechanic" and len({r["impl"] for r in f["versions"].values()}) > 1:
            parts = ", ".join(f"{manifests[b]['release']} {r['impl']}" + (f" ({r['reason']})" if r.get("reason") else "") for b, r in f["versions"].items())
            w(f"- **{f['id']}** {f['name']}: {parts}.")
    w("")
    w("## Inventories not yet collected")
    w("")
    w("Their counts are unknown, not zero.")
    w("")
    for f in feats:
        if f["kind"] == "inventory":
            w(f"- `{f['name']}` ({f['family']}, {f['milestone']}): {f['note']}.")
    w("")
    w("## Cases")
    w("")
    kinds = Counter((c["kind"], c["status"]) for c in ledger["cases"])
    w("| Kind | Status | Cases |")
    w("| --- | --- | ---: |")
    for (kind, status), n in sorted(kinds.items()):
        w(f"| {kind} | {status} | {n} |")
    w("")
    w("Trace cases are the reference traces in `tests/fixtures/`; the other cases are the files of `compatibility/cases/`, "
      "most of them client scripts kept outside this repository.")
    w("")
    w("## Mechanics")
    w("")
    for fam in ledger["families"]:
        w(f"### {fam['id']} {fam['name']}")
        w("")
        w("| Feature | Milestone | " + " | ".join(manifests[b]["release"] for b in bundles) + " | Cases and gaps |")
        w("| --- | --- | " + " | ".join("---" for _ in bundles) + " | --- |")
        for f in feats:
            if f["family"] != fam["id"] or f["kind"] != "mechanic":
                continue
            states = " | ".join(f"{r['impl']}, {r['evidence']}" for r in f["versions"].values())
            cases = sorted({c for r in f["versions"].values() for c in r["cases"]} | set(f.get("cases_planned", [])))
            gaps = sorted({d for r in f["versions"].values() for d in r.get("deviations", [])})
            extra = "; ".join(x for x in [", ".join(f"`{c}`" for c in cases), "; ".join(gaps), f.get("note", "")] if x)
            w(f"| {f['name']} | {f['milestone']} | {states} | {extra} |")
        w("")
    return "\n".join(out).rstrip("\n")


def packages_summary(ledger, manifests):
    """compatibility/PACKAGES.md: the work packages and the mechanics still open in each."""
    bundles = ledger["versions"]
    releases = [manifests[b]["release"] for b in bundles]
    mechanics = [f for f in ledger["features"] if f["kind"] == "mechanic"]
    packages = ledger["packages"]
    out = []
    w = out.append
    w("# Work packages")
    w("")
    w("Generated by `tools/compat_ledger.py` from [`packages.json`](packages.json) and the mechanics in [`families/`](families/); do not edit.")
    w("")
    w("A work package is the unit in which open mechanics of the [ledger](../docs/VANILLA_LEDGER.md) are planned and closed. "
      "A mechanic is open in a version while it is `partial`, `data_only` or `missing` there. "
      "Every open mechanic names the packages its remaining gaps wait for, and a package cannot be marked closed while an open mechanic names it. "
      "A mechanic with gaps in several packages is counted under each of them.")
    w("")
    w("Sizes are relative: S is up to 3 sub-tasks, M 4 to 8, L 9 to 20, XL more or a new subsystem; a package without a size is named only. "
      "A hard prerequisite is a package without which this one cannot be implemented; an evidence prerequisite must exist before it can be verified. "
      "Enumerated resources (blocks, items and the other inventories) are not assigned to packages.")
    w("")
    w("## Packages")
    w("")
    w("| Package | Size | State | Hard prerequisites | Evidence prerequisites | " + " | ".join(f"Open mechanics {r}" for r in releases) + " |")
    w("| --- | --- | --- | --- | --- | " + " | ".join("---:" for _ in bundles) + " |")
    rows = {p["id"]: [f for f in mechanics if p["id"] in f.get("packages", [])] for p in packages}
    for p in packages:
        counts = " | ".join(str(sum(1 for f in rows[p["id"]] if is_open(f, b))) for b in bundles)
        w(f"| {p['id']} {p['title']} | {p['size'] or '—'} | {p['state']} | {', '.join(p['hard']) or '—'} | {', '.join(p['evidence']) or '—'} | {counts} |")
    w("")
    w("## Milestones")
    w("")
    w("Mechanics by milestone label, how many are open, and the packages the open ones name. "
      "The table is computed from the mechanics; it does not record a milestone gate.")
    w("")
    w("| Milestone | Mechanics | " + " | ".join(f"Open {r}" for r in releases) + " | Packages named by its open mechanics |")
    w("| --- | ---: | " + " | ".join("---:" for _ in bundles) + " | --- |")
    order = [p["id"] for p in packages]
    for milestone in MILESTONES:
        fs = [f for f in mechanics if f["milestone"] == milestone]
        named = sorted({q for f in fs if is_open(f) for q in f.get("packages", [])}, key=lambda q: order.index(q) if q in order else len(order))
        counts = " | ".join(str(sum(1 for f in fs if is_open(f, b))) for b in bundles)
        w(f"| {milestone} | {len(fs)} | {counts} | {', '.join(named) or '—'} |")
    w("")
    w("## Open mechanics by package")
    w("")
    for p in packages:
        w(f"### {p['id']} {p['title']}")
        w("")
        for key, lead in (("content", ""), ("evidence_note", "Evidence prerequisites: "), ("note", "")):
            if p.get(key):
                w(lead + p[key].rstrip(".") + ".")
                w("")
        if not rows[p["id"]]:
            w("No open mechanic names this package.")
            w("")
            continue
        w("| Mechanic | Milestone | " + " | ".join(releases) + " | Other packages |")
        w("| --- | --- | " + " | ".join("---" for _ in bundles) + " | --- |")
        for f in rows[p["id"]]:
            states = " | ".join(f["versions"][b]["impl"] for b in bundles)
            others = ", ".join(q for q in f["packages"] if q != p["id"])
            w(f"| `{f['id']}` {f['name']} | {f['milestone']} | {states} | {others or '—'} |")
        w("")
    return "\n".join(out).rstrip("\n")


