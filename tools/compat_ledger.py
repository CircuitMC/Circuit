def validate(ledger, manifests, family_ids, inputs):
    errors = list(inputs.get("source_errors", []))
    bundles = ledger["versions"]
    if bundles != sorted(bundles) or len(set(bundles)) != len(bundles):
        errors.append("versions must be sorted and unique")
    # Manifests agree with the version bundles in the source.
    version_cpp = read_text(os.path.join(ROOT, "src", "contracts", "version.cpp"))
    for b, m in manifests.items():
        block = re.search(r"\.id = \"" + re.escape(b) + r"\"(.*?)\.data_version = (\d+)", version_cpp, re.S)
        if not block:
            errors.append(f"{b}: no bundle in src/contracts/version.cpp")
            continue
        protocol = re.search(r"\.protocol = (\d+)", block.group(1))
        if not protocol or int(protocol.group(1)) != m["protocol"] or int(block.group(2)) != m["data_version"]:
            errors.append(f"{b}: protocol or DataVersion differs from src/contracts/version.cpp")
        packs = re.search(r"\.data_pack_format = (\d+), \.resource_pack_format = (\d+)", block.group(1))
        formats = m.get("pack_formats", {})
        if not packs or (int(packs.group(1)), int(packs.group(2))) != (formats.get("data"), formats.get("resource")):
            errors.append(f"{b}: pack formats differ from src/contracts/version.cpp")
        jar = re.search(r'\.server_jar_sha1 = "([0-9a-f]{40})"', block.group(1))
        servers = [r.get("sha1") for r in m.get("reference_artifacts", []) if r.get("kind") == "server"]
        if not jar or [jar.group(1)] != servers:
            errors.append(f"{b}: server jar SHA-1 differs from src/contracts/version.cpp")
        for key in ("bundle", "release", "protocol", "data_version", "pack_formats", "reference_artifacts", "public_data", "profiles", "sources"):
            if key not in m:
                errors.append(f"{b}: manifest lacks {key}")
        if m.get("bundle") != b:
            errors.append(f"{b}: manifest names bundle {m.get('bundle')}")
        for a in m.get("reference_artifacts", []):
            if not re.fullmatch(r"[0-9a-f]{40}", a.get("sha1", "")) or not re.fullmatch(r"[0-9a-f]{64}", a.get("sha256", "")):
                errors.append(f"{b}: artifact {a.get('kind')} lacks a hash")
        if not any(p["id"] == "default" for p in m.get("profiles", [])):
            errors.append(f"{b}: no default profile")
    commits = {m["public_data"]["commit"] for m in manifests.values()}
    if len(commits) != 1:
        errors.append("manifests pin different minecraft-data commits")
    # Families.
    if family_ids != [f"V{i:02d}" for i in range(1, 37)]:
        errors.append("families must be V01-V36 in order")
    for f in ledger["families"]:
        if not f["milestones"] or any(x not in MILESTONES for x in f["milestones"]):
            errors.append(f"{f['id']}: bad milestones")
    # Cases.
    case_by_id = {c["id"]: c for c in ledger["cases"]}
    case_ids = set(case_by_id)
    for c in ledger["cases"]:
        if c["kind"] not in CASE_KINDS or c["status"] not in CASE_STATUS:
            errors.append(f"case {c['id']}: bad kind or status")
        if not c["versions"] or any(v not in bundles for v in c["versions"]):
            errors.append(f"case {c['id']}: bad versions")
        if (c["kind"] == "planned") != (c["status"] == "planned"):
            errors.append(f"case {c['id']}: planned kind and status must agree")
    # Features.
    seen = set()
    by_family = Counter()
    for f in ledger["features"]:
        fid = f["id"]
        if fid in seen:
            errors.append(f"{fid}: duplicate feature")
        seen.add(fid)
        if f["family"] not in family_ids:
            errors.append(f"{fid}: unknown family {f['family']}")
        by_family[f["family"]] += 1
        if f["milestone"] not in MILESTONES or f["tier"] not in TIERS:
            errors.append(f"{fid}: bad milestone or tier")
        if set(f["versions"]) != set(bundles):
            errors.append(f"{fid}: needs a record for every version")
        for planned in f.get("cases_planned", []):
            if planned not in case_ids:
                errors.append(f"{fid}: dangling planned case {planned}")
        for b, rec in f["versions"].items():
            where = f"{fid} ({b})"
            if rec["impl"] not in IMPL:
                errors.append(f"{where}: implementation state {rec['impl']}")
            if rec["evidence"] not in EVIDENCE:
                errors.append(f"{where}: evidence state {rec['evidence']}")
            if rec["impl"] == "not_applicable" and not rec.get("reason"):
                errors.append(f"{where}: not_applicable needs a reason")
            if rec["impl"] != "not_applicable" and rec.get("reason"):
                errors.append(f"{where}: a reason belongs to not_applicable records")
            for c in rec["cases"]:
                if c not in case_ids:
                    errors.append(f"{where}: dangling case {c}")
            if rec["evidence"] in ("compared", "mismatch", "reference_only") and not rec["cases"]:
                errors.append(f"{where}: evidence {rec['evidence']} needs a case")
            statuses = {case_by_id[c]["status"] for c in rec["cases"] if c in case_by_id}
            kinds = {case_by_id[c]["kind"] for c in rec["cases"] if c in case_by_id}
            if rec["evidence"] == "compared" and rec["cases"] and "passing" not in statuses:
                errors.append(f"{where}: compared evidence needs a passing case")
            if rec["evidence"] == "mismatch" and rec["cases"] and "failing" not in statuses:
                errors.append(f"{where}: mismatch evidence needs a failing case")
            if rec["evidence"] == "reference_only" and rec["cases"] and not kinds & {"official_trace", "black_box", "round_trip"}:
                errors.append(f"{where}: reference_only evidence needs an official observation")
            if rec["evidence"] == "compared" and rec["impl"] not in ("implemented", "partial"):
                errors.append(f"{where}: compared evidence needs an implementation")
            if rec["impl"] == "implemented" and rec.get("deviations"):
                errors.append(f"{where}: an implemented feature cannot list deviations")
            if f["kind"] == "inventory" and rec.get("count") == 0:
                errors.append(f"{where}: an unknown inventory has no count, not zero")
            for c in rec["cases"]:
                case = case_by_id.get(c)
                if case and case["kind"] == "planned" and rec["evidence"] == "compared":
                    errors.append(f"{where}: a planned case cannot support compared evidence")
    for fam in family_ids:
        if by_family[fam] == 0:
            errors.append(f"{fam}: no features")
    # Every enumerated name has exactly one feature.
    for b in bundles:
        inv = inputs["inventories"][b]
        for kind in NAMED_KINDS:
            for name in inv["kinds"][kind]["names"]:
                fid = f"{kind}/{name}" if kind == "packet" else f"{kind}/minecraft:{name}"
                if fid not in seen:
                    errors.append(f"{b}: {kind} {name} has no feature")
        for kind in COUNTED_KINDS:
            if kind not in inv["kinds"]:
                errors.append(f"{b}: inventory lacks {kind}")
    # Version differences are kept: a name in one version only is not_applicable in the other.
    for f in ledger["features"]:
        if f["kind"] in NAMED_KINDS:
            states = {b: r["impl"] for b, r in f["versions"].items()}
            if all(s == "not_applicable" for s in states.values()):
                errors.append(f"{f['id']}: not applicable in every version")
    # Hand-written overrides name real resources.
    resources = inputs["resources"]
    feature_by_id = {f["id"]: f for f in ledger["features"]}
    family_by_id = {f["id"]: f for f in ledger["families"]}
    for kind, entries in resources["overrides"].items():
        for name, spec in entries.items():
            fid = f"{kind}/{name}" if kind == "packet" else f"{kind}/minecraft:{name}"
            if fid not in seen:
                errors.append(f"compatibility/resources/{kind}/{name}.json: {fid} is not in any inventory")
            elif "milestone" in spec and spec["milestone"] not in family_by_id[feature_by_id[fid]["family"]]["milestones"]:
                errors.append(f"{fid}: milestone {spec['milestone']} is not one of family {feature_by_id[fid]['family']}")
            for key in sorted(set(spec) - OVERRIDE_KEYS):
                errors.append(f"{fid}: unknown key {key}")
    for family in inputs["families"]["families"]:
        for m in family["mechanics"]:
            for key in sorted(set(m) - MECHANIC_KEYS):
                errors.append(f"{family['id']}.{m['id']}: unknown key {key}")
    for c in inputs["cases"]["cases"]:
        for key in sorted(set(c) - CASE_KEYS):
            errors.append(f"case {c['id']}: unknown key {key}")
    errors += validate_packages(ledger, inputs["packages"])
    return errors


def is_open(feature, bundle=None):
    """Whether a feature still has work in it, in one version or in any."""
    return any(r["impl"] in OPEN for b, r in feature["versions"].items() if bundle in (None, b))


def validate_packages(ledger, doc):
    """Work packages are well formed; every mechanic that is not implemented
    names known packages, and none of them is closed."""
    errors = []
    by_id = {}
    for p in doc["packages"]:
        pid = p.get("id")
        if not isinstance(pid, str) or not re.fullmatch(r"[A-Z][A-Z0-9]*", pid):
            errors.append(f"package {pid}: bad id")
            continue
        if pid in by_id:
            errors.append(f"package {pid}: defined twice")
        by_id[pid] = p
        if not p.get("title"):
            errors.append(f"package {pid}: needs a title")
        if p.get("size") is not None and p["size"] not in PACKAGE_SIZES:
            errors.append(f"package {pid}: size {p['size']}")
        if p.get("state") not in PACKAGE_STATES:
            errors.append(f"package {pid}: state {p.get('state')}")
        for key in sorted(set(p) - PACKAGE_KEYS):
            errors.append(f"package {pid}: unknown key {key}")
    for pid, p in by_id.items():
        for key in ("hard", "evidence"):
            if not isinstance(p.get(key), list):
                errors.append(f"package {pid}: needs a list of {key} prerequisites")
                continue
            for q in p[key]:
                if q not in by_id or q == pid:
                    errors.append(f"package {pid}: {key} prerequisite {q} is {'the package itself' if q == pid else 'not a package'}")
    # Hard prerequisites give an order of work: no package may need itself through others.
    state = {}

    def visit(pid, path):
        if state.get(pid) == "done":
            return
        if state.get(pid) == "open":
            errors.append("packages: hard prerequisites form a cycle: " + " -> ".join(path[path.index(pid):] + [pid]))
            return
        state[pid] = "open"
        for q in by_id[pid].get("hard") or []:
            if q in by_id and q != pid:
                visit(q, path + [pid])
        state[pid] = "done"
    for pid in by_id:
        visit(pid, [])
    for f in ledger["features"]:
        if f["kind"] != "mechanic":
            continue
        named = f.get("packages", [])
        if not isinstance(named, list) or len(set(named)) != len(named):
            errors.append(f"{f['id']}: packages must be a list without repeats")
            continue
        for q in named:
            if q not in by_id:
                errors.append(f"{f['id']}: unknown package {q}")
            elif by_id[q].get("state") == "closed" and is_open(f):
                errors.append(f"package {q}: closed, but {f['id']} is still open")
        if is_open(f) and not named:
            errors.append(f"{f['id']}: not implemented and names no package")
        if named and not is_open(f):
            errors.append(f"{f['id']}: names a package but is not open in any version")
    return errors


