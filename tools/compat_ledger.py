#!/usr/bin/env python3
"""Builds and checks Circuit's vanilla compatibility ledger.

The ledger records, for every target version, which vanilla features
Circuit implements and what evidence supports each claim. Its inputs:

  compatibility/versions/<bundle>.json   verified version manifests (hand-written)
  compatibility/families.json            families V01-V36, their mechanics and
                                         classification rules (hand-written)
  compatibility/resources.json           status of enumerated resources (hand-written)
  compatibility/cases.json               behavior cases outside the trace fixtures
  compatibility/inventory/<bundle>.json  enumerations of blocks, items, entity
                                         types and other resources (generated by
                                         `inventory` from PrismarineJS minecraft-data
                                         at the pinned commit and from Circuit's
                                         packet and registry tables)
  tests/fixtures/harness*/               reference traces (cases trace/<name>)
  src/server/                            packets the server references

Commands:

  inventory --mcdata <dir>   regenerate the inventories; <dir> holds
                             <release>/tables/*.json and dataPaths.json from
                             minecraft-data at the commit in the manifests
  generate                   write compatibility/ledger.json and docs/VANILLA_LEDGER.md
  check                      validate the inputs and fail if the generated
                             files are out of date (run by tools/check.sh)
"""
import argparse
import json
import os
import re
import sys
from collections import Counter, defaultdict

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
COMPAT = os.path.join(ROOT, "compatibility")
LEDGER = os.path.join(COMPAT, "ledger.json")
SUMMARY = os.path.join(ROOT, "docs", "VANILLA_LEDGER.md")

IMPL = ["implemented", "partial", "data_only", "missing", "not_applicable"]
EVIDENCE = ["compared", "reference_only", "documented", "none", "mismatch"]
TIERS = ["L0", "L1", "L2"]
MILESTONES = [f"C{i}" for i in range(13)]
CASE_KINDS = ["official_trace", "black_box", "real_client", "round_trip", "planned"]
CASE_STATUS = ["passing", "failing", "unsupported", "planned"]
# Resource kinds with one feature per name, and kinds counted only.
NAMED_KINDS = ["block", "item", "entity", "effect", "enchantment", "attribute", "damage_type", "biome", "particle", "command", "packet"]
COUNTED_KINDS = ["block_state", "sound_event", "recipe", "instrument"]


def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def read_text(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def dump(path, data):
    text = json.dumps(data, indent=1, ensure_ascii=False) + "\n"
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


class Failure(Exception):
    pass


# ---- inventory ---------------------------------------------------------------

def snake(name):
    if name == "BadLuck":
        return "unluck"  # the registry name of Bad Luck (minecraft.wiki "Effect")
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def packet_names(protocol):
    path = os.path.join(ROOT, "src", "protocol", f"packets_{protocol}.cpp")
    text = read_text(path)
    states = {"handshaking": "handshaking", "status": "status", "login": "login", "configuration": "configuration", "play": "play"}
    out = []
    for state, bound, name in re.findall(r"\{State::(\w+), Bound::(\w+), 0x[0-9a-fA-F]+, \"(\w+)\"\}", text):
        out.append(f"{states[state]}/{bound}/{name}")
    if not out:
        raise Failure(f"{path}: no packets found")
    return sorted(set(out))


def damage_types():
    text = read_text(os.path.join(ROOT, "src", "server", "registries.cpp"))
    m = re.search(r"\{\"minecraft:damage_type\",\s*\{(.*?)\}\}", text, re.S)
    if not m:
        raise Failure("src/server/registries.cpp: no damage-type registry")
    return sorted(n.split(":", 1)[1] for n in re.findall(r"\"(minecraft:[a-z_]+)\"", m.group(1)))


def cmd_inventory(args):
    paths = load(os.path.join(args.mcdata, "dataPaths.json"))["pc"]
    for bundle in versions():
        manifest = load(os.path.join(COMPAT, "versions", f"{bundle}.json"))
        release = manifest["release"]
        commit = manifest["public_data"]["commit"]
        mapped = paths[release]
        tables = os.path.join(args.mcdata, release, "tables")

        def table(kind):
            return load(os.path.join(tables, f"{kind}.json"))

        def source(kind):
            return {"source": f"minecraft-data {mapped[kind]}/{kind}.json", "exact": mapped[kind] == f"pc/{release}"}

        blocks = table("blocks")
        kinds = {
            "block": {**source("blocks"), "names": sorted(b["name"] for b in blocks)},
            "block_state": {**source("blocks"), "count": sum(b["maxStateId"] - b["minStateId"] + 1 for b in blocks)},
            "item": {**source("items"), "names": sorted(i["name"] for i in table("items") if i["name"] != "air")},
            "entity": {**source("entities"), "names": sorted(e["name"] for e in table("entities"))},
            "effect": {**source("effects"), "names": sorted(snake(e["name"]) for e in table("effects")),
                       "note": "registry names converted from minecraft-data's effect names"},
            "enchantment": {**source("enchantments"), "names": sorted(e["name"] for e in table("enchantments"))},
            "attribute": {**source("attributes"), "names": sorted(a["resource"].split(":", 1)[1] for a in table("attributes"))},
            "biome": {**source("biomes"), "names": sorted(b["name"] for b in table("biomes"))},
            "particle": {**source("particles"), "names": sorted(p["name"] for p in table("particles"))},
            "command": {**source("commands"), "names": sorted(c["name"] for c in table("commands")["root"]["children"]),
                        "note": "top-level commands of the command tree"},
            "sound_event": {**source("sounds"), "count": len(table("sounds"))},
            "recipe": {**source("recipes"), "count": sum(len(v) for v in table("recipes").values()),
                       "note": "crafting recipes as minecraft-data lists them"},
            "instrument": {**source("instruments"), "count": len(table("instruments"))},
            "damage_type": {"source": "src/server/registries.cpp (minecraft.wiki \"Damage type\")", "exact": True, "names": damage_types()},
            "packet": {"source": f"src/protocol/packets_{manifest['protocol']}.cpp (minecraft.wiki protocol tables)", "exact": True,
                       "names": packet_names(manifest["protocol"])},
        }
        dump(os.path.join(COMPAT, "inventory", f"{bundle}.json"),
             {"schema": "circuit-compatibility-inventory-1", "bundle": bundle, "release": release,
              "public_data_commit": commit, "kinds": kinds})
        print(f"{bundle}: " + ", ".join(f"{k} {len(v['names']) if 'names' in v else v['count']}" for k, v in kinds.items()))


# ---- inputs ------------------------------------------------------------------

def versions():
    return load(os.path.join(COMPAT, "families.json"))["versions"]


def per_version(value, bundles, default=None):
    """A field given for both versions, or per version."""
    if isinstance(value, dict):
        return {b: value.get(b, default) for b in bundles}
    return {b: (value if value is not None else default) for b in bundles}


def open_outcomes(directory):
    """Outcomes of the open traces Circuit does not match yet (EXPECTED.txt)."""
    out = {}
    for line in read_text(os.path.join(directory, "EXPECTED.txt")).splitlines():
        if line and not line.startswith("#"):
            name, outcome = line.split(" ")[:2]
            out[name] = {"FAIL": "failing", "UNSUPPORTED": "unsupported"}[outcome]
    return out


def trace_cases(bundles):
    """Every target-version trace is a case: passing ones from the harness
    directories, failing or unsupported ones from the open directories.
    Returns the cases and the blocks each passing trace places."""
    cases = {}
    blocks = defaultdict(set)
    for bundle in bundles:
        schemas = load(os.path.join(COMPAT, "versions", f"{bundle}.json"))["circuit_schemas"]
        sources = [(os.path.join(ROOT, schemas["reference_traces"]), None)]
        if schemas.get("open_traces"):
            open_dir = os.path.join(ROOT, schemas["open_traces"])
            sources.append((open_dir, open_outcomes(open_dir)))
        for d, outcomes in sources:
            for name in sorted(os.listdir(d)):
                if not name.endswith(".ctrace"):
                    continue
                stem = name[: -len(".ctrace")]
                text = read_text(os.path.join(d, name))
                header = dict(line.split(" ", 1) for line in text.splitlines()[:16] if " " in line)
                status = "passing" if outcomes is None else outcomes[name]
                case = cases.setdefault(f"trace/{stem}", {
                    "id": f"trace/{stem}", "kind": "official_trace", "versions": [], "status": status,
                    "location": f"{os.path.relpath(d, ROOT)}/{name}", "description": header.get("title", stem),
                    "mechanisms": header.get("mechanisms", "").split()})
                if case["status"] != status:
                    raise Failure(f"trace/{stem}: {case['status']} on one version, {status} on another")
                case["versions"].append(bundle)
                if status == "passing":
                    for block in set(re.findall(r"minecraft:([a-z_]+)", text)):
                        blocks[(bundle, block)].add(f"trace/{stem}")
    return cases, blocks


def referenced_packets():
    """Packet names the server code looks up, as state/bound/name."""
    out = set()
    for name in sorted(os.listdir(os.path.join(ROOT, "src", "server"))):
        if not name.endswith(".cpp"):
            continue
        text = read_text(os.path.join(ROOT, "src", "server", name))
        for short, state, packet in re.findall(r"\b(cb|sb)\(State::(\w+), \"(\w+)\"\)", text):
            out.add(f"{state}/{'clientbound' if short == 'cb' else 'serverbound'}/{packet}")
        for bound, state, packet in re.findall(r"\b(serverbound|clientbound)\(State::(\w+), \"(\w+)\"\)", text):
            out.add(f"{state}/{bound}/{packet}")
    return out


def classify(rules, kind, name, block_family):
    for family, pattern in rules[kind]:
        if family == "block":
            if name in block_family:
                return block_family[name]
            continue
        if re.search(pattern, name):
            return family
    raise Failure(f"{kind} {name}: no classification rule matches")


# ---- generation --------------------------------------------------------------

def read_inputs():
    """The hand-written and inventory documents, as build() takes them."""
    families_doc = load(os.path.join(COMPAT, "families.json"))
    bundles = families_doc["versions"]
    return {
        "families": families_doc,
        "resources": load(os.path.join(COMPAT, "resources.json")),
        "cases": load(os.path.join(COMPAT, "cases.json")),
        "manifests": {b: load(os.path.join(COMPAT, "versions", f"{b}.json")) for b in bundles},
        "inventories": {b: load(os.path.join(COMPAT, "inventory", f"{b}.json")) for b in bundles},
    }


def build(inputs):
    families_doc = inputs["families"]
    bundles = families_doc["versions"]
    resources = inputs["resources"]
    case_doc = inputs["cases"]
    manifests = inputs["manifests"]
    inventories = inputs["inventories"]
    traces, trace_blocks = trace_cases(bundles)
    cases = dict(traces)
    for c in case_doc["cases"]:
        if c["id"] in cases:
            raise Failure(f"case {c['id']} is defined twice")
        cases[c["id"]] = c
    family_ids = [f["id"] for f in families_doc["families"]]
    family_by_id = {f["id"]: f for f in families_doc["families"]}
    rules = families_doc["classification"]

    features = []

    def add(feature):
        features.append(feature)

    for family in families_doc["families"]:
        for m in family["mechanics"]:
            impl = per_version(m.get("impl"), bundles)
            evidence = per_version(m.get("evidence", "none"), bundles, "none")
            reasons = per_version(m.get("absent_reason", {}), bundles)
            records = {}
            for b in bundles:
                rec = {"impl": impl[b], "evidence": evidence[b]}
                if impl[b] == "not_applicable":
                    rec["reason"] = reasons[b]
                rec["cases"] = [c for c in m.get("cases", []) if b in cases.get(c, {}).get("versions", [b])]
                if m.get("deviations"):
                    rec["deviations"] = m["deviations"]
                records[b] = rec
            feature = {"id": f"{family['id']}.{m['id']}", "family": family["id"], "kind": "mechanic", "name": m["name"],
                       "milestone": m["milestone"], "tier": m.get("tier", "L0"), "versions": records}
            for key in ("note", "cases_planned", "prerequisites"):
                if key in m:
                    feature[key] = m[key]
            add(feature)

    # Enumerated resources: one feature per name and kind, over the union of versions.
    block_family = {}
    for kind in NAMED_KINDS:
        names = sorted(set().union(*(set(inventories[b]["kinds"][kind]["names"]) for b in bundles)))
        defaults = resources["defaults"][kind]
        overrides = resources["overrides"].get(kind, {})
        for name in names:
            family = classify(rules, kind, name, block_family)
            if kind == "block":
                block_family[name] = family
            override = overrides.get(name, {})
            records = {}
            for b in bundles:
                present = name in inventories[b]["kinds"][kind]["names"]
                if not present:
                    records[b] = {"impl": "not_applicable", "evidence": "none",
                                  "reason": f"not in {manifests[b]['release']}", "cases": []}
                    continue
                spec = {**defaults, **override}
                if kind == "packet":
                    if name in REFERENCED and "impl" not in override:
                        spec["impl"] = "partial"
                rec = {"impl": per_version(spec["impl"], bundles)[b], "evidence": per_version(spec.get("evidence", "none"), bundles)[b]}
                linked = list(spec.get("cases", []))
                if kind == "block":
                    linked += sorted(trace_blocks.get((b, name), ()))
                rec["cases"] = sorted({c for c in linked if b in cases.get(c, {}).get("versions", [b])})
                if spec.get("deviations"):
                    rec["deviations"] = spec["deviations"]
                records[b] = rec
            feature = {"id": f"{kind}/{name}" if kind == "packet" else f"{kind}/minecraft:{name}", "family": family,
                       "kind": kind, "name": name, "milestone": family_by_id[family]["milestones"][0], "tier": "L0",
                       "versions": records}
            if override.get("note"):
                feature["note"] = override["note"]
            add(feature)

    for m in families_doc["inventories_unknown"]:
        add({"id": f"inventory/{m['id']}", "family": m["family"], "kind": "inventory", "name": m["id"],
             "milestone": m["milestone"], "tier": "L0", "note": m["note"],
             "versions": {b: {"impl": "missing", "evidence": "none", "count": None, "cases": []} for b in bundles}})

    ledger = {
        "schema": "circuit-compatibility-ledger-1",
        "comment": "Generated by tools/compat_ledger.py; do not edit.",
        "versions": bundles,
        "families": [{"id": f["id"], "name": f["name"], "milestones": f["milestones"]} for f in families_doc["families"]],
        "kind_notes": {k: v["note"] for k, v in resources["defaults"].items() if v.get("note")},
        "inventories": {b: {k: ({"source": v["source"], "exact": v["exact"], "count": len(v["names"]) if "names" in v else v["count"]})
                            for k, v in inventories[b]["kinds"].items()} for b in bundles},
        "cases": [cases[k] for k in sorted(cases)],
        "features": features,
    }
    return ledger, manifests, family_ids


REFERENCED = set()


def ledger_text(ledger):
    """The ledger as JSON with one feature, case or family per line."""
    lines = ["{"]
    keys = list(ledger)
    for i, key in enumerate(keys):
        value = ledger[key]
        tail = "," if i + 1 < len(keys) else ""
        if isinstance(value, list) and value and isinstance(value[0], dict):
            lines.append(f" {json.dumps(key)}: [")
            for j, item in enumerate(value):
                lines.append("  " + json.dumps(item, ensure_ascii=False, sort_keys=True) + ("," if j + 1 < len(value) else ""))
            lines.append(" ]" + tail)
        else:
            lines.append(f" {json.dumps(key)}: " + json.dumps(value, ensure_ascii=False, sort_keys=True) + tail)
    lines.append("}")
    return "\n".join(lines) + "\n"


# ---- validation --------------------------------------------------------------

def validate(ledger, manifests, family_ids, inputs):
    errors = []
    bundles = ledger["versions"]
    if bundles != sorted(bundles) or len(set(bundles)) != len(bundles):
        errors.append("versions must be sorted and unique")
    # Manifests agree with the version bundles in the source.
    version_cpp = read_text(os.path.join(ROOT, "src", "contracts", "version.cpp"))
    for b, m in manifests.items():
        block = re.search(r"\.id = \"" + re.escape(b) + r"\"(.*?)\.data_version = (\d+)", version_cpp, re.S)
        if not block:
            errors.append(f"{b}: no bundle in src/contracts/version.cpp")
            continue
        protocol = re.search(r"\.protocol = (\d+)", block.group(1))
        if not protocol or int(protocol.group(1)) != m["protocol"] or int(block.group(2)) != m["data_version"]:
            errors.append(f"{b}: protocol or DataVersion differs from src/contracts/version.cpp")
        packs = re.search(r"\.data_pack_format = (\d+), \.resource_pack_format = (\d+)", block.group(1))
        formats = m.get("pack_formats", {})
        if not packs or (int(packs.group(1)), int(packs.group(2))) != (formats.get("data"), formats.get("resource")):
            errors.append(f"{b}: pack formats differ from src/contracts/version.cpp")
        jar = re.search(r'\.server_jar_sha1 = "([0-9a-f]{40})"', block.group(1))
        servers = [r.get("sha1") for r in m.get("reference_artifacts", []) if r.get("kind") == "server"]
        if not jar or [jar.group(1)] != servers:
            errors.append(f"{b}: server jar SHA-1 differs from src/contracts/version.cpp")
        for key in ("bundle", "release", "protocol", "data_version", "pack_formats", "reference_artifacts", "public_data", "profiles", "sources"):
            if key not in m:
                errors.append(f"{b}: manifest lacks {key}")
        if m.get("bundle") != b:
            errors.append(f"{b}: manifest names bundle {m.get('bundle')}")
        for a in m.get("reference_artifacts", []):
            if not re.fullmatch(r"[0-9a-f]{40}", a.get("sha1", "")) or not re.fullmatch(r"[0-9a-f]{64}", a.get("sha256", "")):
                errors.append(f"{b}: artifact {a.get('kind')} lacks a hash")
        if not any(p["id"] == "default" for p in m.get("profiles", [])):
            errors.append(f"{b}: no default profile")
    commits = {m["public_data"]["commit"] for m in manifests.values()}
    if len(commits) != 1:
        errors.append("manifests pin different minecraft-data commits")
    # Families.
    if family_ids != [f"V{i:02d}" for i in range(1, 37)]:
        errors.append("families must be V01-V36 in order")
    for f in ledger["families"]:
        if not f["milestones"] or any(x not in MILESTONES for x in f["milestones"]):
            errors.append(f"{f['id']}: bad milestones")
    # Cases.
    case_by_id = {c["id"]: c for c in ledger["cases"]}
    case_ids = set(case_by_id)
    for c in ledger["cases"]:
        if c["kind"] not in CASE_KINDS or c["status"] not in CASE_STATUS:
            errors.append(f"case {c['id']}: bad kind or status")
        if not c["versions"] or any(v not in bundles for v in c["versions"]):
            errors.append(f"case {c['id']}: bad versions")
        if (c["kind"] == "planned") != (c["status"] == "planned"):
            errors.append(f"case {c['id']}: planned kind and status must agree")
    # Features.
    seen = set()
    by_family = Counter()
    for f in ledger["features"]:
        fid = f["id"]
        if fid in seen:
            errors.append(f"{fid}: duplicate feature")
        seen.add(fid)
        if f["family"] not in family_ids:
            errors.append(f"{fid}: unknown family {f['family']}")
        by_family[f["family"]] += 1
        if f["milestone"] not in MILESTONES or f["tier"] not in TIERS:
            errors.append(f"{fid}: bad milestone or tier")
        if set(f["versions"]) != set(bundles):
            errors.append(f"{fid}: needs a record for every version")
        for planned in f.get("cases_planned", []):
            if planned not in case_ids:
                errors.append(f"{fid}: dangling planned case {planned}")
        for b, rec in f["versions"].items():
            where = f"{fid} ({b})"
            if rec["impl"] not in IMPL:
                errors.append(f"{where}: implementation state {rec['impl']}")
            if rec["evidence"] not in EVIDENCE:
                errors.append(f"{where}: evidence state {rec['evidence']}")
            if rec["impl"] == "not_applicable" and not rec.get("reason"):
                errors.append(f"{where}: not_applicable needs a reason")
            if rec["impl"] != "not_applicable" and rec.get("reason"):
                errors.append(f"{where}: a reason belongs to not_applicable records")
            for c in rec["cases"]:
                if c not in case_ids:
                    errors.append(f"{where}: dangling case {c}")
            if rec["evidence"] in ("compared", "mismatch", "reference_only") and not rec["cases"]:
                errors.append(f"{where}: evidence {rec['evidence']} needs a case")
            statuses = {case_by_id[c]["status"] for c in rec["cases"] if c in case_by_id}
            kinds = {case_by_id[c]["kind"] for c in rec["cases"] if c in case_by_id}
            if rec["evidence"] == "compared" and rec["cases"] and "passing" not in statuses:
                errors.append(f"{where}: compared evidence needs a passing case")
            if rec["evidence"] == "mismatch" and rec["cases"] and "failing" not in statuses:
                errors.append(f"{where}: mismatch evidence needs a failing case")
            if rec["evidence"] == "reference_only" and rec["cases"] and not kinds & {"official_trace", "black_box", "round_trip"}:
                errors.append(f"{where}: reference_only evidence needs an official observation")
            if rec["evidence"] == "compared" and rec["impl"] not in ("implemented", "partial"):
                errors.append(f"{where}: compared evidence needs an implementation")
            if rec["impl"] == "implemented" and rec.get("deviations"):
                errors.append(f"{where}: an implemented feature cannot list deviations")
            if f["kind"] == "inventory" and rec.get("count") == 0:
                errors.append(f"{where}: an unknown inventory has no count, not zero")
            for c in rec["cases"]:
                case = case_by_id.get(c)
                if case and case["kind"] == "planned" and rec["evidence"] == "compared":
                    errors.append(f"{where}: a planned case cannot support compared evidence")
    for fam in family_ids:
        if by_family[fam] == 0:
            errors.append(f"{fam}: no features")
    # Every enumerated name has exactly one feature.
    for b in bundles:
        inv = inputs["inventories"][b]
        for kind in NAMED_KINDS:
            for name in inv["kinds"][kind]["names"]:
                fid = f"{kind}/{name}" if kind == "packet" else f"{kind}/minecraft:{name}"
                if fid not in seen:
                    errors.append(f"{b}: {kind} {name} has no feature")
        for kind in COUNTED_KINDS:
            if kind not in inv["kinds"]:
                errors.append(f"{b}: inventory lacks {kind}")
    # Version differences are kept: a name in one version only is not_applicable in the other.
    for f in ledger["features"]:
        if f["kind"] in NAMED_KINDS:
            states = {b: r["impl"] for b, r in f["versions"].items()}
            if all(s == "not_applicable" for s in states.values()):
                errors.append(f"{f['id']}: not applicable in every version")
    # Hand-written overrides name real resources.
    resources = inputs["resources"]
    for kind, entries in resources["overrides"].items():
        for name in entries:
            fid = f"{kind}/{name}" if kind == "packet" else f"{kind}/minecraft:{name}"
            if fid not in seen:
                errors.append(f"resources.json: {fid} is not in any inventory")
    return errors


# ---- summary -----------------------------------------------------------------

def summary(ledger, manifests):
    bundles = ledger["versions"]
    feats = ledger["features"]
    out = []
    w = out.append
    w("# Vanilla compatibility ledger")
    w("")
    w("Generated by `tools/compat_ledger.py` from the files in [`compatibility/`](../compatibility/); do not edit. "
      "The ledger records, for each target version, which vanilla features Circuit implements and what evidence supports each claim. "
      "Its families and milestones are those of the [vanilla completion roadmap](VANILLA_COMPLETION.md).")
    w("")
    w("**Implementation states:** `implemented` (complete for the feature as described), `partial` (some behavior, with listed gaps), "
      "`data_only` (named in registries or storage, with no behavior), `missing`, and `not_applicable` (absent from that version, with the reason). "
      "**Evidence states:** `compared` (Circuit compared with the official server for named cases), `reference_only` (official observations, "
      "Circuit not compared), `documented` (public documentation only), `mismatch` (a comparison shows a difference) and `none`. "
      "Counts of different kinds of features are not comparable, so no overall percentage is given.")
    w("")
    w("## Versions")
    w("")
    w("| | " + " | ".join(manifests[b]["release"] for b in bundles) + " |")
    w("| --- | " + " | ".join("---" for _ in bundles) + " |")
    rows = [
        ("Protocol", lambda m: str(m["protocol"])),
        ("DataVersion", lambda m: str(m["data_version"])),
        ("Data / resource pack format", lambda m: f"{m['pack_formats']['data']} / {m['pack_formats']['resource']}"),
        ("Server jar SHA-1", lambda m: f"`{next(a for a in m['reference_artifacts'] if a['kind'] == 'server')['sha1']}`"),
        ("Client jar SHA-1", lambda m: f"`{next(a for a in m['reference_artifacts'] if a['kind'] == 'client')['sha1']}`"),
        ("Profiles", lambda m: ", ".join(f"{p['id']} ({p['status']})" for p in m["profiles"])),
        ("Public data", lambda m: f"minecraft-data `{m['public_data']['commit'][:8]}`"),
    ]
    for label, f in rows:
        w(f"| {label} | " + " | ".join(f(manifests[b]) for b in bundles) + " |")
    w("")
    w("The values were read from the official jars, whose hashes equal Mojang's published version metadata.")
    w("")
    w("## Families")
    w("")
    w("Feature counts per implementation state, then the number of features with compared evidence. "
      "Each cell lists 1.21.4 / 1.21.8.")
    w("")
    w("| Family | Milestones | Features | Implemented | Partial | Data only | Missing | Not applicable | Compared |")
    w("| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |")
    for fam in ledger["families"]:
        fs = [f for f in feats if f["family"] == fam["id"]]

        def cell(pred):
            return " / ".join(str(sum(1 for f in fs if pred(f["versions"][b]))) for b in bundles)
        w(f"| {fam['id']} {fam['name']} | {', '.join(fam['milestones'])} | {len(fs)} | "
          + " | ".join(cell(lambda r, s=s: r["impl"] == s) for s in ["implemented", "partial", "data_only", "missing", "not_applicable"])
          + f" | {cell(lambda r: r['evidence'] == 'compared')} |")
    w("")
    w("## Enumerated resources")
    w("")
    w("One feature per name. Inventories marked approximate come from a minecraft-data table of an earlier release.")
    w("")
    w("| Kind | Source | Count | Implemented | Partial | Data only | Missing |")
    w("| --- | --- | ---: | ---: | ---: | ---: | ---: |")
    for kind in NAMED_KINDS + COUNTED_KINDS:
        srcs = " / ".join(("" if ledger["inventories"][b][kind]["exact"] else "approximate: ") + ledger["inventories"][b][kind]["source"] for b in bundles)
        count = " / ".join(str(ledger["inventories"][b][kind]["count"]) for b in bundles)
        if kind in COUNTED_KINDS:
            w(f"| {kind} | {srcs} | {count} | — | — | — | — |")
            continue
        fs = [f for f in feats if f["kind"] == kind]

        def cell(state):
            return " / ".join(str(sum(1 for f in fs if f["versions"][b]["impl"] == state)) for b in bundles)
        w(f"| {kind} | {srcs} | {count} | {cell('implemented')} | {cell('partial')} | {cell('data_only')} | {cell('missing')} |")
    w("")
    w("## Version differences")
    w("")
    for kind in NAMED_KINDS:
        only = {b: sorted(f["name"] for f in feats if f["kind"] == kind and all(
            (r["impl"] == "not_applicable") != (o == b) for o, r in f["versions"].items())) for b in bundles}
        if any(only.values()):
            parts = [f"only in {manifests[b]['release']} ({len(n)}): {', '.join(n[:40])}{', …' if len(n) > 40 else ''}" for b, n in only.items() if n]
            w(f"- **{kind}:** " + "; ".join(parts) + ".")
    for f in feats:
        if f["kind"] == "mechanic" and len({r["impl"] for r in f["versions"].values()}) > 1:
            parts = ", ".join(f"{manifests[b]['release']} {r['impl']}" + (f" ({r['reason']})" if r.get("reason") else "") for b, r in f["versions"].items())
            w(f"- **{f['id']}** {f['name']}: {parts}.")
    w("")
    w("## Inventories not yet collected")
    w("")
    w("Their counts are unknown, not zero.")
    w("")
    for f in feats:
        if f["kind"] == "inventory":
            w(f"- `{f['name']}` ({f['family']}, {f['milestone']}): {f['note']}.")
    w("")
    w("## Cases")
    w("")
    kinds = Counter((c["kind"], c["status"]) for c in ledger["cases"])
    w("| Kind | Status | Cases |")
    w("| --- | --- | ---: |")
    for (kind, status), n in sorted(kinds.items()):
        w(f"| {kind} | {status} | {n} |")
    w("")
    w("Trace cases are the reference traces in `tests/fixtures/`; the other cases are listed in `compatibility/cases.json`, "
      "most of them client scripts kept outside this repository.")
    w("")
    w("## Mechanics")
    w("")
    for fam in ledger["families"]:
        w(f"### {fam['id']} {fam['name']}")
        w("")
        w("| Feature | Milestone | " + " | ".join(manifests[b]["release"] for b in bundles) + " | Cases and gaps |")
        w("| --- | --- | " + " | ".join("---" for _ in bundles) + " | --- |")
        for f in feats:
            if f["family"] != fam["id"] or f["kind"] != "mechanic":
                continue
            states = " | ".join(f"{r['impl']}, {r['evidence']}" for r in f["versions"].values())
            cases = sorted({c for r in f["versions"].values() for c in r["cases"]} | set(f.get("cases_planned", [])))
            gaps = sorted({d for r in f["versions"].values() for d in r.get("deviations", [])})
            extra = "; ".join(x for x in [", ".join(f"`{c}`" for c in cases), "; ".join(gaps), f.get("note", "")] if x)
            w(f"| {f['name']} | {f['milestone']} | {states} | {extra} |")
        w("")
    return "\n".join(out).rstrip("\n")


# ---- commands ----------------------------------------------------------------

def produce(inputs=None):
    """Builds and validates the ledger; returns it, the manifests and the errors."""
    REFERENCED.clear()
    REFERENCED.update(referenced_packets())
    inputs = inputs if inputs is not None else read_inputs()
    try:
        ledger, manifests, family_ids = build(inputs)
    except Failure as e:
        return None, inputs["manifests"], [str(e)]
    errors = validate(ledger, manifests, family_ids, inputs)
    return ledger, manifests, errors


def cmd_generate(args):
    ledger, manifests, errors = produce()
    if errors:
        for e in errors:
            print(f"error: {e}", file=sys.stderr)
        sys.exit(1)
    with open(LEDGER, "w", encoding="utf-8") as f:
        f.write(ledger_text(ledger))
    with open(SUMMARY, "w", encoding="utf-8") as f:
        f.write(summary(ledger, manifests) + "\n")
    print(f"{len(ledger['features'])} features, {len(ledger['cases'])} cases")


def cmd_check(args):
    ledger, manifests, errors = produce()
    if ledger is None:
        for e in errors:
            print(f"error: {e}", file=sys.stderr)
        sys.exit(1)
    if not os.path.exists(LEDGER) or read_text(LEDGER) != ledger_text(ledger):
        errors.append("compatibility/ledger.json is out of date: run tools/compat_ledger.py generate")
    if not os.path.exists(SUMMARY) or read_text(SUMMARY) != summary(ledger, manifests) + "\n":
        errors.append("docs/VANILLA_LEDGER.md is out of date: run tools/compat_ledger.py generate")
    for e in errors:
        print(f"error: {e}", file=sys.stderr)
    if errors:
        sys.exit(1)
    print(f"compatibility ledger: {len(ledger['features'])} features, {len(ledger['cases'])} cases, valid")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    inv = sub.add_parser("inventory")
    inv.add_argument("--mcdata", required=True)
    sub.add_parser("generate")
    sub.add_parser("check")
    args = parser.parse_args()
    try:
        {"inventory": cmd_inventory, "generate": cmd_generate, "check": cmd_check}[args.command](args)
    except Failure as e:
        print(f"error: {e}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
