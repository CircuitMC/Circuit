#!/usr/bin/env python3
"""Builds and checks Circuit's vanilla compatibility ledger.

The ledger records, for every target version, which vanilla features
Circuit implements and what evidence supports each claim. Its inputs:

  compatibility/versions/<bundle>.json   verified version manifests (hand-written)
  compatibility/families/<Vnn>/          one family: _family.json and one file per
                                         mechanic (hand-written)
  compatibility/resources/<kind>/        one kind of enumerated resource: _kind.json
                                         with its default status and classification
                                         rules, and one file per resource whose
                                         status differs (hand-written)
  compatibility/cases/                   behavior cases outside the trace fixtures,
                                         one file per case (hand-written)
  compatibility/packages.json            work packages, which the mechanics that
                                         are not implemented name (hand-written)
  compatibility/inventory/<bundle>.json  enumerations of blocks, items, entity
                                         types and other resources (generated by
                                         `inventory` from PrismarineJS minecraft-data
                                         at the pinned commit and from Circuit's
                                         packet and registry tables)
  tests/fixtures/harness*/               reference traces (cases trace/<name>)
  src/server/                            packets the server references

Commands:

  inventory --mcdata <dir>   regenerate the inventories; <dir> holds
                             <release>/tables/*.json and dataPaths.json from
                             minecraft-data at the commit in the manifests
  generate                   write compatibility/ledger.json, docs/VANILLA_LEDGER.md
                             and compatibility/PACKAGES.md
  check                      validate the inputs and fail if the generated
                             files are out of date (run by tools/check.sh);
                             with --sources-only the generated files are not
                             compared, for branches that leave them to the
                             integration
  format                     rewrite the hand-written files in canonical form

The hand-written inputs hold one entry per file, so that branches adding or
changing different entries merge without conflicts; the generated files are
written where branches are integrated.
"""
