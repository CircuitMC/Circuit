#!/usr/bin/env python3
"""Compiles the collision shapes of every block state.

The server checks player movement against block collision shapes. They come
from PrismarineJS minecraft-data (MIT) at the pinned commit that the content
tables use: blockCollisionShapes.json lists, for every block state, a shape
made of boxes in block coordinates; blocks.json gives each block's first
state id. The output maps every target-version block state id to its boxes,
for each protocol version. Usage:

  tools/compile_collision_shapes.py <minecraft-data>/data/pc/1.21.8:772 <minecraft-data>/data/pc/1.21.4:769 \\
      --commit <sha> --output src/server/collision_shapes.cpp
"""
import argparse
import json
import os
import sys

def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("versions", nargs="+", help="<data dir>:<protocol>")
    parser.add_argument("--commit", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()

    boxes = []        # distinct boxes
    box_index = {}
    shapes = []       # distinct shapes, as (first box, count)
    shape_index = {}

    def intern_shape(shape):
        key = tuple(tuple(b) for b in shape)
        if key in shape_index:
            return shape_index[key]
        first = len(boxes)
        for b in key:
            boxes.append(b)
        shape_index[key] = len(shapes)
        shapes.append((first, len(key)))
        return shape_index[key]

    intern_shape([])  # shape 0: no collision
    tables = []
    for spec in args.versions:
        directory, protocol = spec.rsplit(":", 1)
        blocks = {b["name"]: b for b in json.load(open(os.path.join(directory, "blocks.json"), encoding="utf-8"))}
        collision = json.load(open(os.path.join(directory, "blockCollisionShapes.json"), encoding="utf-8"))
        ranges = []
        for name, block in blocks.items():
            if name not in collision["blocks"]:
                sys.exit(f"{directory}: {name} is missing")
            count = block["maxStateId"] - block["minStateId"] + 1
            ids = collision["blocks"][name]
            if isinstance(ids, int):
                ids = [ids] * count
            if len(ids) != count:
                sys.exit(f"{directory}: {name} has {len(ids)} shapes for {count} states")
            per_state = [intern_shape(collision["shapes"][str(i)]) for i in ids]
            ranges.append((block["minStateId"], per_state, name))
        ranges.sort()
        tables.append((int(protocol), os.path.basename(os.path.normpath(directory)), ranges))

    out = [
        "// SPDX-License-Identifier: AGPL-3.0-only",
        "// Generated by tools/compile_collision_shapes.py from PrismarineJS minecraft-data (MIT),",
        f"// commit {args.commit}, blockCollisionShapes.json and blocks.json of "
        + ", ".join(v for _, v, _ in tables) + ". Do not edit by hand.",
        '#include "collision_shapes.hpp"',
        "#include <algorithm>",
        "",
        "namespace circuit::server {",
        "namespace {",
        "constexpr CollisionBox boxes[] = {",
    ]
    for b in boxes:
        out.append("    {" + ", ".join(repr(float(v)) for v in b) + "},")
    if not boxes:
        out.append("    {},")
    out += ["};", "struct Shape {", "    std::uint16_t first, count;", "};", "constexpr Shape shapes[] = {"]
    for first, count in shapes:
        out.append(f"    {{{first}, {count}}},")
    out += ["};", "struct Range {", "    std::int32_t first_state;", "    std::uint16_t states;",
            "    std::uint32_t first; // index into the version's per-state shapes", "};"]
    for protocol, version, ranges in tables:
        flat = []
        out.append(f"// {version}")
        out.append(f"constexpr Range ranges_{protocol}[] = {{")
        for first_state, per_state, name in ranges:
            out.append(f"    {{{first_state}, {len(per_state)}, {len(flat)}}}, // {name}")
            flat += per_state
        out.append("};")
        out.append(f"constexpr std::uint16_t state_shapes_{protocol}[] = {{")
        for i in range(0, len(flat), 24):
            out.append("    " + ", ".join(str(s) for s in flat[i:i + 24]) + ",")
        out.append("};")
    out += [
        "",
        "template <std::size_t N, std::size_t M>",
        "std::optional<std::span<const CollisionBox>> find(const Range (&ranges)[N], const std::uint16_t (&states)[M], std::int32_t id) {",
        "    const auto it = std::upper_bound(std::begin(ranges), std::end(ranges), id,",
        "                                     [](std::int32_t v, const Range& r) { return v < r.first_state; });",
        "    if (it == std::begin(ranges)) return std::nullopt;",
        "    const auto& r = *(it - 1);",
        "    if (id >= r.first_state + r.states) return std::nullopt;",
        "    const auto& shape = shapes[states[r.first + static_cast<std::uint32_t>(id - r.first_state)]];",
        "    return std::span<const CollisionBox>(boxes + shape.first, shape.count);",
        "}",
        "} // namespace",
        "",
        "std::optional<std::span<const CollisionBox>> collision_boxes(std::int32_t protocol, std::int32_t state_id) noexcept {",
    ]
    for protocol, _, _ in tables:
        out.append(f"    if (protocol == {protocol}) return find(ranges_{protocol}, state_shapes_{protocol}, state_id);")
    out += ["    return std::nullopt;", "}", "", "} // namespace circuit::server", ""]
    open(args.output, "w", encoding="utf-8").write("\n".join(out))
    print(f"{len(shapes)} shapes, {len(boxes)} boxes")


if __name__ == "__main__":
    main()
