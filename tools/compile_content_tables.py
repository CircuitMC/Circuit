#!/usr/bin/env python3
"""Compiles block-state, item and entity-type tables for one protocol version.

The block-state registry order is not given by the protocol pages themselves;
minecraft.wiki's protocol FAQ points to the public PrismarineJS minecraft-data
dataset (MIT) for such data. This tool reads its blocks.json, items.json and
entities.json at a pinned commit and writes a C++ source file. Block states of
one block are consecutive; properties vary with the last one fastest and
boolean properties list true before false (both checked against each block's
documented default state). Usage:

  tools/compile_content_tables.py <minecraft-data checkout or download dir>/data/pc/1.21.8 \\
      --protocol 772 --commit <sha> --output src/protocol/content_772.cpp
"""
import argparse
import json
import os
import sys


def values_of(state):
    if state["type"] == "bool":
        return ["true", "false"]
    if state["type"] == "int" and not state.get("values"):
        return [str(i) for i in range(state["num_values"])]
    return list(state["values"])


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("data_dir")
    parser.add_argument("--protocol", type=int, required=True)
    parser.add_argument("--commit", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()

    load = lambda name: json.load(open(os.path.join(args.data_dir, f"{name}.json"), encoding="utf-8"))
    blocks, items, entities = load("blocks"), load("items"), load("entities")

    expected_state = 0
    block_lines = []
    for b in sorted(blocks, key=lambda b: b["minStateId"]):
        if b["minStateId"] != expected_state:
            sys.exit(f"state ids of {b['name']} do not follow the previous block")
        props = [(s["name"], values_of(s)) for s in b.get("states", [])]
        count = 1
        for _, values in props:
            count *= len(values)
        if b["maxStateId"] - b["minStateId"] + 1 != count:
            sys.exit(f"{b['name']}: {count} states from properties, {b['maxStateId'] - b['minStateId'] + 1} ids")
        if not (b["minStateId"] <= b["defaultState"] <= b["maxStateId"]):
            sys.exit(f"{b['name']}: default state outside its range")
        expected_state = b["maxStateId"] + 1
        prop_text = ", ".join("{\"%s\", {%s}}" % (n, ", ".join(f"\"{v}\"" for v in vs)) for n, vs in props)
        block_lines.append(f"    {{\"minecraft:{b['name']}\", {b['minStateId']}, {b['defaultState']}, {{{prop_text}}}}},")

    item_lines = [f"    {{{i['id']}, \"minecraft:{i['name']}\"}}," for i in sorted(items, key=lambda i: i["id"])]
    if [i["id"] for i in sorted(items, key=lambda i: i["id"])] != list(range(len(items))):
        sys.exit("item ids are not contiguous")
    entity_lines = [f"    {{{e['id']}, \"minecraft:{e['name']}\"}}," for e in sorted(entities, key=lambda e: e["id"])]

    out = [
        "// SPDX-License-Identifier: AGPL-3.0-only",
        "// Generated by tools/compile_content_tables.py from PrismarineJS minecraft-data (MIT),",
        f"// commit {args.commit}, data/pc for protocol {args.protocol}. Do not edit by hand.",
        '#include "content_tables.hpp"',
        "",
        "namespace circuit::protocol::detail {",
        "",
        f"const ContentTable content_{args.protocol}{{{args.protocol}, \"{args.commit}\", {expected_state},",
        "  {",
        *block_lines,
        "  },",
        "  {",
        *item_lines,
        "  },",
        "  {",
        *entity_lines,
        "  }};",
        "",
        "} // namespace circuit::protocol::detail",
        "",
    ]
    open(args.output, "w", encoding="utf-8").write("\n".join(out))
    print(f"{len(blocks)} blocks ({expected_state} states), {len(items)} items, {len(entities)} entity types -> {args.output}")


if __name__ == "__main__":
    main()
