#!/usr/bin/env python3
"""Writes the constructed workloads of docs/PERFORMANCE.md as .wl files.

usage: workloads.py [output directory]     (default: build/bench/workloads)

The format is described in tools/bench/README.md. Three families:

  iso_*      A square of chunks with one group of machines in every chunk.
             Every block lies at chunk-local 3 to 12, so no rule reads or
             writes a neighbouring column: the best case for column ownership.
  idle_16_*  The same square with a floor, the server's default game rules and
             one player, and nothing else.
  players_N  N idle players 640 blocks apart on a stone floor, each with the
             tickets of view distance 10 and simulation distance 10.

The output is a function of this script alone; the files are not committed.
"""
import sys
from pathlib import Path

LAMP = "minecraft:redstone_lamp[lit=false]"
STONE = "minecraft:stone"
GRASS = "minecraft:grass_block[snowy=false]"
CHEST = "minecraft:chest[facing=north,type=single,waterlogged=false]"
# A floor with the game rules a server starts with and one player in the middle
# of the 16 by 16 square.
SERVER_RULES = ["rule randomTickSpeed 3", "rule doDaylightCycle 1", "rule doWeatherCycle 1"]
SERVER_16 = SERVER_RULES + ["presence 1 136.5 1 136.5"]


def observer(facing):
    return f"minecraft:observer[facing={facing},powered=false]"


def header(size, tickets="one", extra=()):
    lines = [f"# generated by tools/bench/workloads.py: {size}x{size} chunks, one machine group per chunk", "settle 60"]
    if tickets == "one":
        r = size // 2
        lines.append(f"ticket 1 {r} {r} {r} forced")
    else:
        lines += [f"ticket {cx * size + cz + 1} {cx} {cz} 0 forced" for cx in range(size) for cz in range(size)]
    return lines + list(extra)


def chunks(size):
    return [(cx, cz) for cx in range(size) for cz in range(size)]


def clock(x, y, z, a=LAMP, b=LAMP):
    """An observer clock along +x: a at x, observers at x+1 and x+2, b at x+3."""
    return [f"at 0 set {x} {y} {z} {a}", f"at 0 set {x + 3} {y} {z} {b}", f"at 0 set {x + 1} {y} {z} {observer('east')}",
            f"at 1 set {x + 2} {y} {z} {observer('west')}"]


def iso_observer(size, per_chunk=4, tickets="one", extra=()):
    """Redstone without random draws: observer clocks with lamps."""
    lines = header(size, tickets, extra)
    for cx, cz in chunks(size):
        for k in range(per_chunk):
            lines += clock(cx * 16 + 4, 0, cz * 16 + 3 + 3 * k)
    return lines


def iso_dust(size, extra=()):
    """Redstone without random draws: an observer clock driving a 6-block dust line and a lamp."""
    lines = header(size, "one", extra)
    for cx, cz in chunks(size):
        for k in range(2):
            x, z = cx * 16 + 3, cz * 16 + 5 + 5 * k
            lines += [f"at 0 set {x} 0 {z} {observer('east')}", f"at 1 set {x + 1} 0 {z} {observer('west')}"]
            for d in range(2, 8):
                lines += [f"at 0 set {x + d} -1 {z} {STONE}", f"at 0 set {x + d} 0 {z} minecraft:redstone_wire[power=0]"]
            lines.append(f"at 0 set {x + 8} 0 {z} {LAMP}")
    return lines


def iso_piston(size, per_chunk=2, extra=()):
    """Draws from the level's random source: observer-driven sticky pistons, one draw per move."""
    lines = header(size, "one", extra)
    for cx, cz in chunks(size):
        for k in range(per_chunk):
            x, z = cx * 16 + 4, cz * 16 + 3 + 5 * k
            lines += [f"at 0 set {x} 0 {z} {observer('east')}",
                      f"at 0 set {x + 2} 0 {z} minecraft:sticky_piston[extended=false,facing=south]",
                      f"at 0 set {x + 2} 0 {z + 1} {STONE}", f"at 1 set {x + 1} 0 {z} {observer('west')}"]
    return lines


def iso_dropper(size, extra=()):
    """Draws from the level's random source: clocked droppers push items up into hoppers that feed them back."""
    lines = header(size, "one", extra)
    up = "minecraft:dropper[facing=up,triggered=false]"
    down = "minecraft:hopper[enabled=true,facing=down]"
    for cx, cz in chunks(size):
        for k in range(2):
            x, z = cx * 16 + 4, cz * 16 + 4 + 6 * k
            lines += clock(x, 0, z, up, up)
            for dx in (0, 3):
                lines.append(f"at 0 set {x + dx} 1 {z} {down}")
                lines += [f"at 0 insert {x + dx} 0 {z} {slot} {STONE} 64" for slot in range(3)]
    return lines


def iso_items(size, extra=()):
    """Draws and spawns item entities: clocked droppers eject items that fall into hoppers."""
    lines = header(size, "one", extra)
    down = "minecraft:dropper[facing=down,triggered=false]"
    for cx, cz in chunks(size):
        x, z = cx * 16 + 4, cz * 16 + 8
        lines += clock(x, 2, z, down, down)
        lines += [f"at 0 set {x} 0 {z} minecraft:hopper[enabled=true,facing=east]", f"at 0 set {x + 1} 0 {z} {CHEST}",
                  f"at 0 set {x + 3} 0 {z} minecraft:hopper[enabled=true,facing=west]", f"at 0 set {x + 2} 0 {z} {CHEST}"]
        for dx in (0, 3):
            lines += [f"at 0 insert {x + dx} 2 {z} {slot} {STONE} 64" for slot in range(9)]
    return lines


def iso_hopper(size, extra=()):
    """Block entities without random draws: a chest feeding an 8-hopper chain into a chest."""
    lines = header(size, "one", extra)
    for cx, cz in chunks(size):
        for k in range(2):
            x, z = cx * 16 + 3, cz * 16 + 5 + 5 * k
            lines.append(f"at 0 set {x} 1 {z} {CHEST}")
            lines += [f"at 0 insert {x} 1 {z} {slot} {STONE} 64" for slot in range(27)]
            lines += [f"at 0 set {x + d} 0 {z} minecraft:hopper[enabled=true,facing=east]" for d in range(8)]
            lines.append(f"at 0 set {x + 8} 0 {z} {CHEST}")
    return lines


def players(count):
    """Idle players in rows of eight, 40 chunks apart, standing on the floor."""
    lines = ["# idle server-like world: N players far apart, view distance 10 (loading ticket radius 10 and a simulation ticket), "
             "stone floor, default rules from tick 2", "settle 60", f"floor -8 {STONE}"] + SERVER_RULES
    for k in range(count):
        cx, cz = 40 * (k % 8), 40 * (k // 8)
        lines += [f"ticket {k + 1} {cx} {cz} 10 player", f"presence {k + 1} {cx * 16 + 8.5} -7 {cz * 16 + 8.5}"]
    return lines


def workloads():
    floor = lambda block: [f"floor -8 {block}"] + SERVER_16
    out = {
        "iso_observer_16": iso_observer(16),
        "iso_dust_16": iso_dust(16),
        "iso_hopper_16": iso_hopper(16),
        "iso_piston_16": iso_piston(16),
        "iso_dropper_16": iso_dropper(16),
        "iso_items_16": iso_items(16),
        # Variants: one ticket per chunk, a larger square, and the two machine
        # kinds on a grass floor under the server's game rules.
        "iso_observer_16_tickets256": iso_observer(16, tickets="per_chunk"),
        "iso_observer_32": iso_observer(32),
        "iso_piston_32": iso_piston(32),
        "iso_observer_16_grass": iso_observer(16, extra=floor(GRASS)),
        "iso_piston_16_grass": iso_piston(16, extra=floor(GRASS)),
        # Small worlds, for the threshold below which a phase runs on the calling thread.
        "iso_observer_4x1": iso_observer(4, per_chunk=1),
        "iso_observer_4x4": iso_observer(4),
        "iso_observer_8": iso_observer(8),
        "iso_hopper_2": iso_hopper(2),
        "iso_dust_4": iso_dust(4),
        "idle_16_fixture_rules": header(16),
        "idle_16_stone": header(16, extra=floor(STONE)),
        "idle_16_grass": header(16, extra=floor(GRASS)),
    }
    for count in (1, 4, 16, 64):
        out[f"players_{count}"] = players(count)
    return out


def main():
    root = Path(__file__).resolve().parents[2]
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else root / "build" / "bench" / "workloads"
    out.mkdir(parents=True, exist_ok=True)
    for name, lines in workloads().items():
        (out / f"{name}.wl").write_text("\n".join(lines) + "\n")
    print(f"{len(workloads())} workloads in {out}")


if __name__ == "__main__":
    main()
