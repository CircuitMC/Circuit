#!/usr/bin/env python3
"""Compiles the reference rules' item registry from public item lists.

The rule set's items are the union of the items of every supported version,
read from PrismarineJS minecraft-data (MIT) at the pinned commit that the
content tables use: names, maximum stack sizes and durability. Ids 1-8 keep
the items the earlier rule sets numbered; the others follow in name order.
Items that the rules give no behavior to are inert: they can be stored,
moved, dropped and picked up. Usage:

  tools/compile_item_registry.py <minecraft-data>/data/pc/1.21.8 <minecraft-data>/data/pc/1.21.4 \\
      --commit <sha> --source src/gameplay/item_registry.cpp --header include/circuit/gameplay/item_ids.hpp
"""
import argparse
import json
import os
import sys

# Ids of the earlier rule sets; they keep their numbers.
FIXED = ["stone", "redstone", "wheat", "iron_ingot", "lever", "repeater", "comparator", "wheat_seeds"]


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("data_dirs", nargs="+")
    parser.add_argument("--commit", required=True)
    parser.add_argument("--source", required=True)
    parser.add_argument("--header", required=True)
    args = parser.parse_args()

    items = {}
    for d in args.data_dirs:
        for i in json.load(open(os.path.join(d, "items.json"), encoding="utf-8")):
            if i["name"] == "air":
                continue
            entry = (i["stackSize"], i.get("maxDurability", 0))
            if i["name"] in items and items[i["name"]] != entry:
                sys.exit(f"{i['name']}: stack size or durability differs between versions")
            items[i["name"]] = entry
    for name in FIXED:
        if name not in items:
            sys.exit(f"fixed item {name} is missing")
    order = FIXED + sorted(n for n in items if n not in FIXED)
    if len(order) > 65535:
        sys.exit("too many items")

    versions = ", ".join(os.path.basename(os.path.normpath(d)) for d in args.data_dirs)
    head = [
        "// SPDX-License-Identifier: AGPL-3.0-only",
        "// Generated by tools/compile_item_registry.py from PrismarineJS minecraft-data (MIT),",
        f"// commit {args.commit}, items of {versions}. Do not edit by hand.",
    ]
    source = head + [
        "#include <circuit/gameplay/items.hpp>",
        "#include <unordered_map>",
        "",
        "namespace circuit::gameplay::items {",
        "namespace {",
        "constexpr ItemInfo table[] = {",
    ]
    for name in order:
        stack, durability = items[name]
        source.append(f"    {{\"minecraft:{name}\", {stack}, {durability}}},")
    source += [
        "};",
        "} // namespace",
        "",
        "std::span<const ItemInfo> registry() noexcept { return table; }",
        "",
        "std::optional<std::uint16_t> by_name(std::string_view name) noexcept {",
        "    // Built once; names are unique.",
        "    static const auto index = [] {",
        "        std::unordered_map<std::string_view, std::uint16_t> m;",
        "        for (std::size_t i = 0; i < std::size(table); ++i) m.emplace(table[i].name, static_cast<std::uint16_t>(i + 1));",
        "        return m;",
        "    }();",
        "    const auto it = index.find(name);",
        "    if (it == index.end()) return std::nullopt;",
        "    return it->second;",
        "}",
        "",
        "} // namespace circuit::gameplay::items",
        "",
    ]
    header = head + [
        "#pragma once",
        "#include <cstdint>",
        "",
        "// Rule ids of the items, as constants named after the items.",
        "namespace circuit::gameplay::items {",
    ]
    for index, name in enumerate(order):
        header.append(f"inline constexpr std::uint16_t {name} = {index + 1};")
    header += [f"inline constexpr std::uint16_t max_id = {len(order)};", "} // namespace circuit::gameplay::items", ""]
    open(args.source, "w", encoding="utf-8").write("\n".join(source))
    open(args.header, "w", encoding="utf-8").write("\n".join(header))
    print(f"{len(order)} items")


if __name__ == "__main__":
    main()
