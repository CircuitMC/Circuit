#!/usr/bin/env python3
"""Generates the circuit-trace workload skeletons used for profiling (M2.6).

Each workload is a skeleton with setup actions only: the fixture's ticks are the
settle time, after which a profiler measures a fixed number of further ticks.
"""
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "tests" / "fixtures" / "workloads"
LAMP = "minecraft:redstone_lamp[lit=false]"
STONE = "minecraft:stone"


def observer(facing):
    return f"minecraft:observer[facing={facing},powered=false]"


def write(name, title, mechanisms, area, ticks, actions):
    lines = ["circuit-trace 1", f"# Profiling workload generated by tools/generate_workloads.py.",
             f"title {title}", "game-version 1.21.8", "source circuit_reference", "harness -",
             f"mechanisms {mechanisms}", "area " + " ".join(map(str, area)), f"ticks {ticks}", ""]
    lines += [f"at {t} {a}" for t, a in sorted(actions, key=lambda x: x[0])]
    (OUT / f"{name}.ctrace").write_text("\n".join(lines) + "\n")


def observer_clocks():
    actions = []
    for i in range(16):
        for j in range(16):
            x, z = 8 * i, 8 * j
            actions += [(0, f"set {x} 0 {z} {LAMP}"), (0, f"set {x + 3} 0 {z} {LAMP}"),
                        (0, f"set {x + 1} 0 {z} {observer('east')}"), (1, f"set {x + 2} 0 {z} {observer('west')}")]
    write("observer_clocks", "256 observer clocks with lamps", "observer redstone_lamp scheduled_ticks",
          (0, 0, 0, 127, 0, 127), 40, actions)


def dust_clocks():
    actions = []
    for j in range(16):
        for x0 in (0, 32, 64, 96):
            z = 8 * j
            actions += [(0, f"set {x0} 0 {z} {observer('east')}"), (1, f"set {x0 + 1} 0 {z} {observer('west')}")]
            for x in range(x0 + 2, x0 + 16):
                actions += [(0, f"set {x} -1 {z} {STONE}"), (0, f"set {x} 0 {z} minecraft:redstone_wire[power=0]")]
            actions.append((0, f"set {x0 + 16} 0 {z} {LAMP}"))
    write("dust_clocks", "64 observer clocks driving 14-block dust lines", "redstone_wire observer neighbor_updates",
          (0, -1, 0, 127, 0, 127), 40, actions)


def hopper_lines():
    actions = []
    for j in range(32):
        for x0 in (0, 32):
            z = 2 * j
            actions.append((0, f"set {x0} 1 {z} minecraft:chest[facing=north,type=single,waterlogged=false]"))
            actions += [(0, f"insert {x0} 1 {z} {k} {STONE} 64") for k in range(27)]
            actions += [(0, f"set {x0 + k} 0 {z} minecraft:hopper[enabled=true,facing=east]") for k in range(8)]
            actions.append((0, f"set {x0 + 8} 0 {z} minecraft:chest[facing=north,type=single,waterlogged=false]"))
    write("hopper_lines", "64 eight-hopper item chains", "hopper block_entity_order", (0, 0, 0, 63, 1, 63), 40, actions)


def piston_engines():
    actions = []
    for i in range(16):
        for j in range(8):
            x, z = 8 * i, 16 * j
            actions += [(0, f"set {x} 0 {z} {observer('east')}"), (0, f"set {x + 2} 0 {z} minecraft:sticky_piston[extended=false,facing=south]"),
                        (0, f"set {x + 2} 0 {z + 1} {STONE}"), (1, f"set {x + 1} 0 {z} {observer('west')}")]
    write("piston_engines", "128 observer-driven sticky pistons", "piston block_events observer", (0, 0, 0, 127, 0, 127), 40, actions)


def water_flood():
    actions = [(0, f"set {x} 0 {z} {STONE}") for x in range(64) for z in range(64)]
    actions += [(1, f"set {x} 1 {z} minecraft:water[level=0]") for x in range(4, 64, 16) for z in range(4, 64, 16)]
    write("water_flood", "16 water sources on a 64 by 64 floor", "water scheduled_ticks", (0, 0, 0, 63, 1, 63), 3, actions)


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    for generate in (observer_clocks, dust_clocks, hopper_lines, piston_engines, water_flood):
        generate()
